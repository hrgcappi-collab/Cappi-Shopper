#!/usr/bin/env python3
"""Хто що може в боті.

    перевіряючий   проходить перевірки, бачить свої
    адмін          те саме плюс отримує звіти, бачить усі перевірки,
                   додає і прибирає людей

Список живе у ~/.shopper/доступ.json і правиться з бота. При першому
запуску збирається з TELEGRAM_ALLOWED_IDS — усі звідти стають адмінами,
інакше після старту нікому було б роздавати права.

Чужа людина, що написала боту, бачить відмову, а адміни — картку з кнопкою
«Додати як перевіряючого»: так підключення нового тайного гостя — одне
натискання, без пошуку його id.
"""
import сховище

ФАЙЛ = "доступ.json"
РОЛІ = ["перевіряючий", "адмін"]


def _всі():
    люди = сховище.json_читати(ФАЙЛ, None)
    if люди is None:
        люди = {}
        for uid in сховище.конфіг().get("TELEGRAM_ALLOWED_IDS", "").split(","):
            uid = uid.strip()
            if uid:
                люди[uid] = {"роль": "адмін", "імя": ""}
        сховище.json_писати(ФАЙЛ, люди)
    return люди


def роль(uid):
    return _всі().get(str(uid), {}).get("роль")


def можна(uid, що):
    р = роль(uid)
    if що == "перевіряти":
        return р in РОЛІ
    if що == "адмінити":
        return р == "адмін"
    return False


def дати(uid, роль_, імя=""):
    люди = _всі()
    старе = люди.get(str(uid), {})
    люди[str(uid)] = {"роль": роль_, "імя": імя or старе.get("імя", "")}
    сховище.json_писати(ФАЙЛ, люди)


def прибрати(uid):
    люди = _всі()
    люди.pop(str(uid), None)
    сховище.json_писати(ФАЙЛ, люди)


def запамятати_імя(uid, імя):
    люди = _всі()
    if str(uid) in люди and імя and люди[str(uid)].get("імя") != імя:
        люди[str(uid)]["імя"] = імя
        сховище.json_писати(ФАЙЛ, люди)


def адміни():
    return [int(uid) for uid, п in _всі().items() if п.get("роль") == "адмін"]


def список():
    return sorted(_всі().items(), key=lambda kv: (kv[1].get("роль") != "адмін", kv[1].get("імя", "")))
