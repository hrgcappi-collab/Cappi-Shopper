#!/usr/bin/env python3
"""Хто що може в боті.

Ролі з ТЗ (розділ 21):

    тайник        зовнішній виконавець: завдання, анкета, підтримка, виплати
    координатор   підтримка тайників, форс-мажори
    маркетолог    власник програми: приймає рішення, правила, блеклист
    адмін         переказує гроші, тисне «Виплачено»
    спостерігач   керівник точки — читання по своїй філії, право оскаржити
    власник       усе (COO)

Тайники живуть у реєстрі (тайники.py), а не тут: тут — лише люди
компанії. Список у ~/.shopper/доступ.json, правиться з бота. При першому
запуску збирається з TELEGRAM_ALLOWED_IDS — усі звідти стають власниками,
інакше після старту нікому було б роздавати права.
"""
import сховище

ФАЙЛ = "доступ.json"
РОЛІ = ["координатор", "маркетолог", "адмін", "спостерігач", "власник"]

ПРАВА = {
    "координатор": {"підтримка"},
    "маркетолог": {"підтримка", "вирішувати", "правила", "реєстр", "хвилі", "дивитись"},
    "адмін": {"платити", "дивитись"},
    "спостерігач": {"дивитись"},
    "власник": {"підтримка", "вирішувати", "правила", "реєстр", "хвилі", "дивитись", "платити", "доступ"},
}


def _всі():
    люди = сховище.json_читати(ФАЙЛ, None)
    if люди is None:
        люди = {}
        for uid in сховище.конфіг().get("TELEGRAM_ALLOWED_IDS", "").split(","):
            uid = uid.strip()
            if uid:
                люди[uid] = {"роль": "власник", "імя": ""}
        сховище.json_писати(ФАЙЛ, люди)
    return люди


def картка(uid):
    return _всі().get(str(uid))


def роль(uid):
    return (картка(uid) or {}).get("роль")


def можна(uid, що):
    return що in ПРАВА.get(роль(uid) or "", set())


def філія_спостерігача(uid):
    return (картка(uid) or {}).get("філія")


def дати(uid, роль_, імя="", філія=None):
    люди = _всі()
    старе = люди.get(str(uid), {})
    люди[str(uid)] = {"роль": роль_, "імя": імя or старе.get("імя", "")}
    if філія:
        люди[str(uid)]["філія"] = філія
    сховище.json_писати(ФАЙЛ, люди)


def прибрати(uid):
    люди = _всі()
    люди.pop(str(uid), None)
    сховище.json_писати(ФАЙЛ, люди)


def запамятати_імя(uid, імя):
    люди = _всі()
    if str(uid) in люди and імя and люди[str(uid)].get("імя") != імя:
        люди[str(uid)]["імя"] = імя
        сховище.json_писати(ФАЙЛ, люди)


def з_правом(що):
    return [int(uid) for uid, п in _всі().items() if що in ПРАВА.get(п.get("роль", ""), set())]


def список():
    return sorted(_всі().items(), key=lambda kv: (РОЛІ.index(kv[1].get("роль", "спостерігач")) * -1, kv[1].get("імя", "")))
