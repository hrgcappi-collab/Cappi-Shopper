#!/usr/bin/env python3
"""Із відповідей — бали, з балів — текст звіту.

Бал рахується тільки за кроки з «вагою». Решта (час, сума, фото,
коментар) — факти для звіту, не для оцінки.

    оцінка   1–5 → частка від ваги: 5 = повна вага, 1 = нуль
    так_ні   збіг з «очікується» — повна вага, інакше нуль
    вибір    «бали» варіанта відносно найбільшого з них

«Критично» — крок, провал якого позначається у звіті окремо, навіть якщо
загальний відсоток пристойний: неповний заказ — це не «мінус три бали»,
це дзвінок гостю і повернення грошей.

Штучний інтелект сюди ще не підключено: `мозок.висновок` повертає None,
і звіт іде без нього. Коли з'явиться ключ — тут нічого міняти не треба.
"""
import html
from datetime import datetime

import перевірка

ЗІРКИ = {5: "★★★★★", 4: "★★★★☆", 3: "★★★☆☆", 2: "★★☆☆☆", 1: "★☆☆☆☆"}


def е(т):
    return html.escape(str(т if т is not None else ""), quote=False)


def _бал(к, в):
    """(отримано, максимум) для кроку; (0, 0) — крок не оцінюється."""
    вага = к.get("вага")
    if not вага or в is None:
        return 0, 0
    т = к["тип"]
    if т == "оцінка":
        return вага * (в - 1) / 4, вага
    if т == "так_ні":
        return (вага if в == к.get("очікується") else 0), вага
    if т == "вибір":
        бали = к.get("бали") or {}
        найб = max(бали.values()) if бали else 0
        return (вага * бали.get(в, 0) / найб if найб else 0), вага
    return 0, 0


def оцінити(с):
    """Підсумок по розділах і загалом. Числа — у відсотках, 0–100."""
    відп = с["відповіді"]
    розділи = {}
    критичні = []
    всього = [0.0, 0.0]
    for к in перевірка.кроки(с):
        в = відп.get(к["код"])
        отр, макс = _бал(к, в)
        if макс:
            р = розділи.setdefault(к["розділ"], {"назва": к["розділ_назва"], "отримано": 0.0, "максимум": 0.0})
            р["отримано"] += отр
            р["максимум"] += макс
            всього[0] += отр
            всього[1] += макс
        if к.get("критично") and в is not None and отр < макс:
            критичні.append(к["код"])
    for р in розділи.values():
        р["відсоток"] = round(100 * р["отримано"] / р["максимум"]) if р["максимум"] else None
    return {
        "відсоток": round(100 * всього[0] / всього[1]) if всього[1] else None,
        "розділи": розділи,
        "критичні": критичні,
        "час_доставки_хв": _час_доставки(відп),
    }


def _час_доставки(відп):
    """Від оформлення до дверей, якщо обидві мітки є. Коди — зі сценарію."""
    try:
        а = datetime.fromisoformat(відп["час_замовлення"])
        б = datetime.fromisoformat(відп["час_отримання"])
        return max(0, round((б - а).total_seconds() / 60))
    except (KeyError, ValueError, TypeError):
        return None


def _показати(к, в):
    т = к["тип"]
    if в is None:
        return "—"
    if т == "оцінка":
        return ЗІРКИ.get(в, str(в))
    if т == "так_ні":
        return "так" if в else "ні"
    if т == "час":
        try:
            return datetime.fromisoformat(в).strftime("%H:%M")
        except ValueError:
            return е(в)
    if т == "число":
        return str(int(в)) if float(в).is_integer() else str(в)
    if т == "фото":
        return "📷"
    return е(в)


def підсумок_для_гостя(с):
    """Що бачить перевіряючий перед відправкою — усе, що вніс, щоб виправити."""
    рядки = [f"<b>{е(с['філія'])}</b> · {е(с['канал'])}", ""]
    останній = None
    for к in перевірка.кроки(с):
        if к["розділ"] != останній:
            рядки.append(f"<b>{е(к['розділ_назва'])}</b>")
            останній = к["розділ"]
        рядки.append(f"  {е(к['питання'])}: {_показати(к, с['відповіді'].get(к['код']))}")
    о = оцінити(с)
    рядки.append("")
    if о["відсоток"] is not None:
        рядки.append(f"Попередня оцінка: <b>{о['відсоток']}%</b>")
    return "\n".join(рядки)


def текст_звіту(з):
    """Звіт для адмінів: коротко зверху, подробиці нижче."""
    о = з["оцінка"]
    хто = з["хто"].get("імя") or з["хто"].get("id")
    коли = datetime.fromisoformat(з["завершено"]).strftime("%d.%m %H:%M")
    рядки = [f"🕵️ <b>Тайний гість · {е(з['філія'])} · {е(з['канал'])}</b>",
             f"{коли} · {е(хто)}", ""]
    if о["відсоток"] is not None:
        рядки.append(f"Оцінка: <b>{о['відсоток']}%</b>")
    for р in о["розділи"].values():
        if р["відсоток"] is not None:
            рядки.append(f"  {е(р['назва'])}: {р['відсоток']}%")
    if о["час_доставки_хв"] is not None:
        обіц = з["відповіді"].get("обіцяний_час")
        д = f"Доставка: <b>{о['час_доставки_хв']} хв</b>"
        if обіц:
            д += f" (обіцяли {int(обіц)})"
            if о["час_доставки_хв"] > обіц:
                d = о["час_доставки_хв"] - int(обіц)
                д += f" — запізнення {d} хв"
        рядки.append(д)
    if о["критичні"]:
        рядки.append("")
        рядки.append("🔴 <b>Критично:</b>")
        for код in о["критичні"]:
            к = next((k for k in перевірка.кроки(з) if k["код"] == код), {})
            рядки.append(f"  • {е(к.get('питання', код))}")
    сума = з["відповіді"].get("сума")
    if сума:
        рядки.append(f"Чек: {_показати({'тип': 'число'}, сума)} грн")
    ком = з["відповіді"].get("коментар")
    if ком:
        рядки.append("")
        рядки.append(f"💬 {е(ком)}")
    рядки.append("")
    рядки.append("<b>Подробиці</b>")
    останній = None
    for к in перевірка.кроки(з):
        if к["тип"] in ("фото",):
            continue
        if к["розділ"] != останній:
            рядки.append(f"<i>{е(к['розділ_назва'])}</i>")
            останній = к["розділ"]
        рядки.append(f"  {е(к['питання'])}: {_показати(к, з['відповіді'].get(к['код']))}")
    return "\n".join(рядки)


def фото(з):
    """file_id усіх фото у перевірці — щоб додати їх до звіту."""
    return [(к["питання"], з["відповіді"][к["код"]])
            for к in перевірка.кроки(з)
            if к["тип"] == "фото" and з["відповіді"].get(к["код"])]


def рядок_журналу(з):
    о = з["оцінка"]
    коли = datetime.fromisoformat(з["завершено"]).strftime("%d.%m %H:%M")
    оц = f"{о['відсоток']}%" if о["відсоток"] is not None else "—"
    крит = " 🔴" if о["критичні"] else ""
    return f"{коли} · {е(з['філія'])} · {е(з['канал'])} · <b>{оц}</b>{крит}"
