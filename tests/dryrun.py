#!/usr/bin/env python3
"""Повний цикл без Telegram: підміняємо tg(), граємо за тайників,
маркетолога й адміна, дивимось, що бот відповідає.

    python3 tests/dryrun.py        → друкує діалог і «прогін пройдено»
"""
import os
import shutil
import sys
import tempfile
from datetime import datetime, timedelta

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)

ВЛАСНИК = 395687418
Т1, Т2, Т3 = 1001, 1002, 1003
ГРУПА = -1001


def звіти_для_core():
    import звіти
    return звіти.для_core()


def прогнати(тихо=False):
    дім = tempfile.mkdtemp(prefix="shopper-")
    os.environ["SHOPPER_HOME"] = дім
    os.environ["TELEGRAM_ALLOWED_IDS"] = str(ВЛАСНИК)
    os.environ["TELEGRAM_BOT_TOKEN"] = "тест"
    os.environ["OPENAI_API_KEY"] = ""
    # Свіжі модулі проєкту: усі, чий файл лежить у папці бота. Інакше,
    # наприклад, провокації тримають старий «перевірки» зі старою папкою даних.
    for м, мод in list(sys.modules.items()):
        if getattr(мод, "__file__", None) and os.path.dirname(os.path.abspath(мод.__file__)) == ТУТ:
            sys.modules.pop(м)
    import bot, access, тайники, перевірки, хвилі, форма, налаштування, планувальник, виплати, syrve, приймання, loopa
    loopa.негатив = lambda днів=30: {"групи": {"кухня": 12, "курєр": 4}, "філії": {"Лазарєва": 9}, "всього": 16, "днів": 30}

    # Фальшивий Syrve: одне замовлення з номера тайника — те, що є в завданні.
    os.environ["SYRVE_CLOUD_URL"] = "https://syrve.test"
    os.environ["SYRVE_CLOUD_API_KEY"] = "k"
    os.environ["SYRVE_ORG_ID"] = "o"
    syrve_вимкнено = {"так": False}

    def fake_orders(телефон, дата, днів=1):
        if syrve_вимкнено["так"]:
            raise syrve.Недоступний("тест: недоступний")
        п = перевірки.тайника(Т1) or перевірки.історія_тайника(Т1)[-1]
        оф = п["анкета"]["відповіді"].get("час_оформлення") or f"{дата}T19:00:00"
        t0 = datetime.fromisoformat(оф)
        f = lambda t: t.strftime("%Y-%m-%d %H:%M:%S")
        return [{"id": "x1", "number": 8909, "status": "Closed", "conception": {"name": "1 Лазарева"},
                 "whenCreated": f(t0), "whenConfirmed": f(t0 + timedelta(minutes=3)), "whenSended": f(t0 + timedelta(minutes=30)),
                 "whenDelivered": f(t0 + timedelta(minutes=52)), "completeBefore": f(t0 + timedelta(minutes=45)), "sum": 520.0,
                 "items": [{"product": {"id": п["завдання"]["позиції"][0]["id"], "name": п["завдання"]["позиції"][0]["назва"]}, "amount": 1, "resultSum": 280},
                           {"product": {"id": "zzz", "name": "Маргарита"}, "amount": 1, "resultSum": 240}],
                 "operator": {"name": "Оля"}, "courierInfo": {"courier": {"name": "Ігор"}}}]

    syrve.замовлення_за_телефоном = fake_orders

    надіслано = []

    def fake_tg(method, **p):
        if method in ("sendMessage", "sendPhoto"):
            надіслано.append((p["chat_id"], p.get("text") or f"[фото {p.get('photo')}]", p.get("reply_markup")))
            if not тихо:
                print(f"→ {p['chat_id']}: {(p.get('text') or '[фото]')[:300]}")
                for ряд in (p.get("reply_markup") or {}).get("inline_keyboard", []):
                    print("     " + " | ".join(f"[{к['text']}]" for к in ряд))
        return {"ok": True, "result": {}}

    bot.tg = fake_tg

    def останнє(chat):
        return next((t for c, t, _ in reversed(надіслано) if c == chat), "")

    def кнопки(chat):
        for c, _, rm in reversed(надіслано):
            if c == chat and rm and rm.get("inline_keyboard"):
                return [к["callback_data"] + "|" + к["text"] for ряд in rm["inline_keyboard"] for к in ряд]
        return []

    def текст(chat, т, **зайве):
        if not тихо:
            print(f"{chat} ← {т}")
        bot.повідомлення({"chat": {"id": chat}, "from": {"id": chat, "first_name": f"Людина{chat}", "username": f"u{chat}"}, "text": т, **зайве})

    def кнопка(chat, дані, хто=None):
        if not тихо:
            print(f"{chat} ← ({дані})")
        bot.кнопка({"message": {"chat": {"id": chat}}, "data": дані, "from": {"id": хто or chat, "first_name": "К"}})

    def заповнити(chat, підправити=None):
        """Проходить поточну форму, відповідаючи правдоподібно."""
        підправити = підправити or {}
        for _ in range(200):
            с = форма.поточна(chat)
            if not с:
                return
            к = форма.крок(с)
            if к is None:
                break
            if к["код"] in підправити:
                v = підправити[к["код"]]
                if к["тип"] in ("вибір", "так_ні", "оцінка"):
                    кнопка(chat, f"в:{'так' if v is True else 'ні' if v is False else v}")
                else:
                    текст(chat, str(v))
                continue
            т = к["тип"]
            if т == "оцінка":
                кнопка(chat, "в:4")
            elif т == "так_ні":
                кнопка(chat, "в:так" if к.get("очікується") in (True, None) else "в:ні")
            elif т == "згода":
                кнопка(chat, "в:так")
            elif т == "вибір" and к.get("кілька"):
                кнопка(chat, f"м:{к['варіанти'][0]}")
                кнопка(chat, "м:готово")
            elif т == "вибір":
                кнопка(chat, f"в:{к.get('правильно') or к['варіанти'][0]}")
            elif т == "час":
                кнопка(chat, "в:зараз")
            elif т == "фото":
                текст(chat, "", photo=[{"file_id": f"AgAC-{chat}-{к['код']}", "file_unique_id": f"U{chat}{к['код']}"}])
            elif т == "контакт":
                текст(chat, "", contact={"phone_number": "+380671234567"})
            elif т == "число":
                текст(chat, {"сума_замовлення": "560", "обіцяний_час": "45", "сайт_хвилин": "6", "сам_очікування": "3"}.get(к["код"], str(к.get("норма") or 5)))
            else:
                текст(chat, "Все було добре, кур'єр ввічливий, піца гаряча, роли рівні. Один соус забули." if к["код"] == "заг_враження" else "коментар " + к["код"])
        с = форма.поточна(chat)
        if с:
            assert "Надіслати" in str(кнопки(chat)) or forma_done(chat), f"форма не дійшла до підсумку: {форма.крок(с)}"
            кнопка(chat, "з:надіслати")

    def forma_done(chat):
        return форма.крок(форма.поточна(chat)) is None

    def завести_тайника(chat):
        текст(chat, "/start")
        assert форма.поточна(chat) and форма.поточна(chat)["ключ"] == "реєстрація"
        заповнити(chat)
        assert тайники.картка(chat)["статус"] == "кандидат"
        assert "Кандидат" in останнє(ВЛАСНИК)
        кнопка(ВЛАСНИК, f"т:активувати:{chat}")
        assert тайники.картка(chat)["статус"] == "активний"
        кнопка(chat, "т:тест")
        заповнити(chat)
        assert тайники.готовий_до_завдань(chat), тайники.чого_бракує(chat)

    # ---------------- 1. кандидати → активні
    завести_тайника(Т1)
    завести_тайника(Т2)
    завести_тайника(Т3)
    assert тайники.номер(Т1) == "Т-001"

    # неправильний тест
    текст(9009, "/start"); заповнити(9009); кнопка(ВЛАСНИК, "т:активувати:9009"); кнопка(9009, "т:тест")
    заповнити(9009, підправити={"тест_1": "Кажу правду"})
    assert not тайники.готовий_до_завдань(9009) and "Пройти ще раз" in str(кнопки(9009))

    # ---------------- 2. хвиля
    текст(ВЛАСНИК, bot.КНОПКИ["хвилі"])
    кнопка(ВЛАСНИК, "х:створити")
    х = хвилі.усі("чернетка")[0]
    assert len(х["слоти"]) == 2 and {с["філія"] for с in х["слоти"]} == {"Лазарєва", "Левітана"}
    кнопка(ВЛАСНИК, f"х:відкрити:{х['id']}")
    assert "Нова хвиля" in останнє(Т1) and "Відгукнутись" in str(кнопки(Т1))

    кнопка(Т1, f"х:відгук:{х['id']}")
    п1 = перевірки.тайника(Т1)
    assert п1 and п1["статус"] == "завдання видано" and len(п1["завдання"]["позиції"]) == 2
    assert "Завдання" in останнє(Т1) and "Приймаю" in str(кнопки(Т1))
    assert п1["завдання"]["провокація"] and п1["завдання"]["провокація"]["адресат"] == "курєр", "перше завдання — з провокацією для кур'єра"
    assert "Сценарій (курєр)" in останнє(Т1) and "скаржаться на: кухня (12)" in останнє(Т1)
    кнопка(Т2, f"х:відгук:{х['id']}")
    п2 = перевірки.тайника(Т2)
    assert п2 and хвилі.дай(х["id"])["статус"] == "набір закрито"
    assert not п2["завдання"]["провокація"], "друге поспіль — без провокації (1 з 3)"
    кнопка(Т3, f"х:відгук:{х['id']}")
    assert перевірки.тайника(Т3) is None and Т3 in хвилі.дай(х["id"])["черга"] and "в черзі" in останнє(Т3)

    # ---------------- 3. акцепт / відмова / резерв
    кнопка(Т1, f"а:так:{п1['id']}")
    assert перевірки.дай(п1["id"])["статус"] == "акцептовано"
    кнопка(Т2, f"а:ні:{п2['id']}")
    assert перевірки.дай(п2["id"])["статус"] == "зрив"
    п3 = перевірки.тайника(Т3)
    assert п3 and п3["статус"] == "завдання видано", "слот мав перейти Т3 із черги"

    # тайм-аут акцепту через планувальник
    п3["акцепт_до"] = (datetime.now() - timedelta(hours=1)).isoformat(timespec="seconds")
    перевірки.зберегти(п3)
    планувальник.тік()
    assert перевірки.дай(п3["id"])["статус"] == "зрив" and "вийшов" in останнє(Т3)
    assert хвилі.дай(х["id"])["статус"] == "відкрито набір"

    # ---------------- 4. анкета Т1: етап «до»
    текст(Т1, bot.КНОПКИ["анкета"])
    assert форма.поточна(Т1)["ключ"] == "анкета:до"
    заповнити(Т1)
    п1 = перевірки.дай(п1["id"])
    assert п1["статус"] == "в виконанні" and п1["анкета"]["відповіді"]["обіцяний_час"] == 45

    # чернетка: почали «після», скасували — внесене лишилось
    текст(Т1, bot.КНОПКИ["анкета"])
    assert форма.поточна(Т1)["ключ"] == "анкета:після"
    кнопка(Т1, "в:зараз")                     # час_отримання
    текст(Т1, bot.ХІД["скасувати"])
    assert перевірки.дай(п1["id"])["анкета"]["відповіді"].get("час_отримання")

    # етап «після» з контактом оператора і холодною піцою (критично)
    текст(Т1, bot.КНОПКИ["анкета"])
    заповнити(Т1, підправити={"контакт_оператор": True, "кух_температура": "Холодна", "оп_допи": False})
    п1 = перевірки.дай(п1["id"])
    assert п1["статус"] == "на ревю", (п1["статус"], п1.get("приймання"))
    assert п1["syrve"]["знайдено"] and п1["syrve"]["замовлення"]["номер"] == 8909
    assert п1["syrve"]["збіги"]["філія відповідає завданню"] is True
    assert п1["syrve"]["збіги"]["склад відповідає завданню"] is True, п1["syrve"]
    assert п1["syrve"]["збіги"]["сума збігається з анкетою"] is False   # 560 в анкеті проти 520 у Syrve
    assert "Syrve: замовлення №8909" in останнє(ВЛАСНИК)
    assert п1["анкета"]["відповіді"].get("оп_тон"), "блок оператора мав з'явитись після «контакт: так»"
    assert п1["анкета"]["відповіді"].get("пров_регламент") is True, "блок провокації мав бути в анкеті"
    assert any(k.startswith("стр_") for k in п1["анкета"]["відповіді"]), "міні-блоки страв з еталонів"
    assert "Рекомендація агента" in останнє(ВЛАСНИК) and f"р:прийняти:{п1['id']}" in str(кнопки(ВЛАСНИК))

    # ---------------- 5. підключаємо чат кухні і приймаємо
    текст(ГРУПА, "/чат", **{})
    bot.повідомлення({"chat": {"id": ГРУПА}, "from": {"id": ВЛАСНИК, "first_name": "Д"}, "text": "/чат"})
    кнопка(ГРУПА, f"к:кухня_{п1['філія']}", хто=ВЛАСНИК)
    assert налаштування.чат(f"кухня_{п1['філія']}") == ГРУПА
    кнопка(ГРУПА, "к:адмін", хто=ВЛАСНИК)

    до = len(надіслано)
    кнопка(ВЛАСНИК, f"р:прийняти:{п1['id']}")
    п1 = перевірки.дай(п1["id"])
    assert п1["статус"] == "прийнята" and п1["оцінка"]["зона"] == "червона", п1["оцінка"]
    assert п1["оцінка"]["групи"]["кухня"]["відсоток"] == 0, "холодна страва — незалік кухні"
    assert п1["оцінка"]["групи"]["оператор"]["відсоток"] < 100
    assert п1["оцінка"]["групи"]["провокація"]["відсоток"] is not None
    assert "для Loopa" in "".join(t for c, t, _ in надіслано[до:] if c == ВЛАСНИК) and loopa.тікети()
    assert п1["виплата"]["статус"] == "у черзі на виплату" and п1["виплата"]["компенсація"] == 520 and п1["виплата"]["джерело_чека"] == "Syrve"
    assert п1["оцінка"]["час_доставки_хв"] == 52 and п1["оцінка"]["запізнення_хв"] == 7 and п1["оцінка"]["джерело_таймингу"] == "Syrve"
    у_групу = [t for c, t, _ in надіслано[до:] if c == ГРУПА]
    assert any("Червона зона" in t and "Кухня" in t for t in у_групу), у_групу
    assert any("Заявка В-" in t for t in у_групу), "картка виплати мала піти в адмін-чат"
    assert not any("Людина1001" in t or "+38067" in t for t in у_групу), "персоналії в чаті!"
    до_т1 = [t for c, t, _ in надіслано[до:] if c == Т1]
    assert any("прийнято" in t.lower() for t in до_т1) and any("вкажи реквізити" in t for t in до_т1)
    assert тайники.картка(Т1)["перевірок"] == 1 and тайники.у_кулдауні(Т1)

    # арбітраж із чату
    кнопка(ГРУПА, f"о:не_згодні:{п1['id']}", хто=777)
    assert "Арбітраж" in останнє(ВЛАСНИК)

    # ---------------- 6. виплата
    кнопка(ГРУПА, f"г:виплатити:{п1['id']}", хто=ВЛАСНИК)
    assert перевірки.дай(п1["id"])["виплата"]["статус"] == "виплачена" and "Гроші прийшли" in str(кнопки(Т1))
    кнопка(Т1, f"г:прийшли:{п1['id']}")
    assert перевірки.дай(п1["id"])["статус"] == "закрита"

    # ---------------- 7. підтримка, форс-мажор, налаштування, екрани
    текст(Т1, bot.КНОПКИ["підтримка"])
    текст(Т1, "позиції немає в наявності, що робити?")
    assert "не заміняй" in останнє(Т1) and "🆘" in останнє(ВЛАСНИК)
    кнопка(ВЛАСНИК, f"с:відповісти:{Т1}")
    текст(ВЛАСНИК, "Візьми Каліфорнію замість")
    assert "Координатор" in останнє(Т1)

    текст(ВЛАСНИК, bot.КНОПКИ["налаштування"])
    кнопка(ВЛАСНИК, "н:ставка_за_анкету")
    текст(ВЛАСНИК, "150")
    assert налаштування.дай("ставка_за_анкету") == 150

    кнопка(ВЛАСНИК, "н:канал:Телефон")
    assert "Телефон" in налаштування.дай("канали_активні")
    текст(ВЛАСНИК, "/тікети")
    assert "Червона зона" in останнє(ВЛАСНИК)
    for кн in ("черга", "перевірки", "тайники", "виплати", "матриця", "доступ", "хвилі"):
        текст(ВЛАСНИК, bot.КНОПКИ[кн])
    текст(ВЛАСНИК, "/дайджест")
    assert "Тайний гість" in останнє(ВЛАСНИК)
    for кн in ("завдання", "виплати_мої", "правила", "статус"):
        текст(Т1, bot.КНОПКИ[кн])
    кнопка(ВЛАСНИК, f"т:картка:{Т1}")
    assert "Т-001" in останнє(ВЛАСНИК)
    кнопка(ВЛАСНИК, f"р:анкета:{п1['id']}")
    кнопка(ВЛАСНИК, f"р:фото:{п1['id']}")
    assert "[фото" in останнє(ВЛАСНИК)

    # імпорт файлів: еталони від шефа, співробітники, новинки, зміни
    import імпорт, еталони
    файли = {
        "еталони.csv": "id;назва;категорія;статус;версія;ціна;шматків;упаковка;температура;склад;комплектність;ознаки;фірмове;syrve_id;запущено\n"
                       ";Філадельфія;суші та роли;опубліковано;2;330;8;пенал;холодна;лосось, сир;імбир|васабі;Зріз рівний|Норі не розмокла;Товстий лосось;;\n"
                       ";Маргарита;піца;опубліковано;1;250;8;коробка;гаряча;;серветки;Борт піднявся|Низ пропечений;;;\n"
                       ";Новий рол;суші та роли;опубліковано;1;300;8;пенал;холодна;;;;;;\n",
        "співробітники.txt": "# HR\n+380671234567\n0501112233\n",
        "новинки.csv": "назва;syrve_id;тип;від;до\nМаргарита;;акція;2026-09-01;2027-01-01\n",
        "зміни.csv": "дата;філія;роль;імя\n" + п1["вікно"]["дата"] + ";Лазарєва;кухар;Петро\n",
    }
    bot.завантажити = lambda file_id: файли[file_id]
