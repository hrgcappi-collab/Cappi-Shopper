#!/usr/bin/env python3
"""Прогін перевірки без Telegram: підміняємо tg(), годуємо бота
повідомленнями і кнопками, дивимось, що він відповідає.

    python3 tests/dryrun.py        → друкує весь діалог
"""
import os
import shutil
import sys
import tempfile

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)

ГІСТЬ = 1001
АДМІН = 395687418


def прогнати(тихо=False):
    дім = tempfile.mkdtemp(prefix="shopper-")
    os.environ["SHOPPER_HOME"] = дім
    os.environ["TELEGRAM_ALLOWED_IDS"] = str(АДМІН)
    os.environ["TELEGRAM_BOT_TOKEN"] = "тест"
    for м in ("сховище", "access", "перевірка", "звіт", "bot"):
        sys.modules.pop(м, None)
    import bot, access, перевірка

    надіслано = []

    def fake_tg(method, **p):
        if method in ("sendMessage", "sendPhoto"):
            надіслано.append((p["chat_id"], p.get("text") or f"[фото {p.get('photo')}]", p.get("reply_markup")))
            if not тихо:
                print(f"→ {p['chat_id']}: {p.get('text') or '[фото]'}")
                rm = p.get("reply_markup") or {}
                for ряд in rm.get("inline_keyboard", []):
                    print("     " + " | ".join(f"[{к['text']}]" for к in ряд))
        return {"ok": True, "result": {}}

    bot.tg = fake_tg

    def текст(chat, т, **зайве):
        if not тихо:
            print(f"{chat} ← {т}")
        bot.повідомлення({"chat": {"id": chat}, "from": {"id": chat, "first_name": "Тест"}, "text": т, **зайве})

    def кнопка(chat, дані):
        if not тихо:
            print(f"{chat} ← ({дані})")
        bot.кнопка({"message": {"chat": {"id": chat}}, "data": дані, "from": {"id": chat}})

    # Чужий стукає — адмін бачить картку і додає його.
    текст(ГІСТЬ, "/start")
    assert any(c == АДМІН and "Стукає" in t for c, t, _ in надіслано), "адмін не отримав запит"
    кнопка(АДМІН, f"д:дати:{ГІСТЬ}:перевіряючий")
    assert access.можна(ГІСТЬ, "перевіряти")

    # Перевірка по телефону: усі кроки, включно з операторськими.
    текст(ГІСТЬ, bot.КНОПКИ["нова"])
    кнопка(ГІСТЬ, "ф:Лазарєва")
    кнопка(ГІСТЬ, "к:Телефон")
    с = перевірка.поточна(ГІСТЬ)
    assert с["філія"] == "Лазарєва" and с["канал"] == "Телефон"
    кроки = перевірка.кроки(с)
    assert any(к["код"] == "оператор_ввічливий" for к in кроки), "крок каналу «Телефон» не показано"

    кнопка(ГІСТЬ, "в:зараз")                 # час_замовлення
    текст(ГІСТЬ, "абв")                      # сума — не число
    assert "число" in надіслано[-1][1]
    текст(ГІСТЬ, "450")                      # сума
    текст(ГІСТЬ, "40")                       # обіцяний час
    кнопка(ГІСТЬ, "в:так")                   # оператор ввічливий
    кнопка(ГІСТЬ, "в:ні")                    # допродаж
    текст(ГІСТЬ, bot.ХІД["назад"])           # повернулись на допродаж
    assert перевірка.крок(перевірка.поточна(ГІСТЬ))["код"] == "допродаж"
    кнопка(ГІСТЬ, "в:так")
    кнопка(ГІСТЬ, "в:зараз")                 # час_отримання
    кнопка(ГІСТЬ, "в:4")                     # кур'єр
    кнопка(ГІСТЬ, "в:так")                   # розрахунок
    текст(ГІСТЬ, bot.ХІД["пропустити"])      # фото пакета — можна
    кнопка(ГІСТЬ, "в:ні")                    # комплектність — критично!
    кнопка(ГІСТЬ, "в:Тепла")                 # температура
    кнопка(ГІСТЬ, "в:5")                     # упаковка
    кнопка(ГІСТЬ, "в:5")                     # смак
    текст(ГІСТЬ, "нема фото", photo=[{"file_id": "AgAC-test"}])   # фото страви
    кнопка(ГІСТЬ, "в:3")                     # загальне
    текст(ГІСТЬ, bot.ХІД["пропустити"])      # коментар
    assert "Перевір, чи все правильно" in надіслано[-1][1]

    # Виправили загальне враження на 4 і відправили.
    кнопка(ГІСТЬ, "з:виправити")
    кнопка(ГІСТЬ, "п:загальне")
    кнопка(ГІСТЬ, "в:4")
    текст(ГІСТЬ, bot.ХІД["пропустити"])
    кнопка(ГІСТЬ, "з:надіслати")

    звіти = [t for c, t, _ in надіслано if c == АДМІН and "Тайний гість" in t]
    assert len(звіти) == 1, "адмін мав отримати рівно один звіт"
    assert "Критично" in звіти[0], "провал комплектності мав позначитись"
    assert any("[фото AgAC-test]" == t for c, t, _ in надіслано if c == АДМІН), "фото не додано до звіту"
    assert перевірка.поточна(ГІСТЬ) is None
    з = перевірка.журнал()[-1]
    assert з["оцінка"]["критичні"] == ["комплектність"]
    assert з["відповіді"]["загальне"] == 4
    assert "Дякую" in надіслано[-1][1]

    # Сайт: операторських кроків немає.
    текст(ГІСТЬ, bot.КНОПКИ["нова"])
    кнопка(ГІСТЬ, "ф:Левітана")
    кнопка(ГІСТЬ, "к:Сайт")
    assert not any(к["код"] == "оператор_ввічливий" for к in перевірка.кроки(перевірка.поточна(ГІСТЬ)))
    текст(ГІСТЬ, bot.ХІД["скасувати"])
    assert перевірка.поточна(ГІСТЬ) is None

    текст(ГІСТЬ, bot.КНОПКИ["мої"])
    assert "Лазарєва" in надіслано[-1][1]
    текст(АДМІН, bot.КНОПКИ["усі"])
    assert "Тест" in надіслано[-1][1]

    shutil.rmtree(дім, ignore_errors=True)
    if not тихо:
        print("\nпрогін пройдено")


if __name__ == "__main__":
    прогнати()
