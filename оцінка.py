#!/usr/bin/env python3
"""Бали з відповідей — за ТЗ розділ 14.

- Кожна група (кухня, упаковка, кур'єр, оператор, сайт, точка) рахується
  окремо, 0–100, і не змішується з іншими: кухня не тягне вниз сервіс.
- Загальна — зважене середнє груп за вагами з налаштувань.
- «Не застосовно» вилучається зі знаменника.
- Суб'єктивні питання (смак, тон) — з половинною вагою.
- Критична помилка дає незалік групи незалежно від балів: сторонній
  предмет, холодна страва, протікання, не та страва, відсутня позиція,
  запізнення понад поріг, грубість.
- Зони: зелена / жовта / червона за порогами з налаштувань.
"""
from datetime import datetime

import анкета
import налаштування
import форма

ГРУПИ = {"кухня": "Кухня і страви", "упаковка": "Упаковка", "курєр": "Кур'єр",
         "оператор": "Оператор", "сайт": "Сайт і застосунок", "точка": "Точка (самовивіз)",
         "підтримка": "Підтримка", "провокація": "Реакція на нестандартне"}


def _бал(к, в):
    """(отримано, максимум, критично) для одного кроку. (0, 0, False) — не оцінюється."""
    if в is None or в == форма.НД:
        return 0, 0, False
    т = к["тип"]
    вага = к.get("вага") or 0
    if к.get("субєктивно"):
        вага = вага / 2
    критично = False
    if т == "так_ні":
        if к.get("критично") and в != к.get("очікується"):
            критично = True
        return (вага if в == к.get("очікується") else 0), вага, критично
    if т == "оцінка":
        return вага * (в - 1) / 4, вага, False
    if т == "вибір":
        if в in (к.get("нд_варіанти") or []):
            return 0, 0, False
        if в in (к.get("критичні") or []):
            критично = True
        бали = к.get("бали") or {}
        найб = max(бали.values()) if бали else 0
        return (вага * бали.get(в, 0) / найб if найб else 0), вага, критично
    if т == "число" and к.get("норма"):
        # Кількість шматків: збіглося — повна вага, ні — нуль.
        return (вага if float(в) == float(к["норма"]) else 0), вага, False
    return 0, 0, False


def час_доставки_хв(в):
    try:
        а = datetime.fromisoformat(в["час_оформлення"])
        б = datetime.fromisoformat(в["час_отримання"])
        return max(0, round((б - а).total_seconds() / 60))
    except (KeyError, ValueError, TypeError):
        return None


def запізнення_хв(в):
    факт = час_доставки_хв(в)
    обіц = в.get("обіцяний_час")
    if факт is None or not обіц:
        return None
    return факт - int(обіц)


def зона(відсоток):
    if відсоток is None:
        return None
    з = налаштування.дай("зони")
    if відсоток >= з["зелена"]:
        return "зелена"
    if відсоток >= з["жовта"]:
        return "жовта"
    return "червона"


def порахувати(п):
    """Повний розрахунок для перевірки. Зберігається у п['оцінка']."""
    в = п.get("анкета", {}).get("відповіді", {})
    групи = {}
    критичні = []
    for к in анкета.усі_кроки(п):
        г = к.get("група")
        if not г:
            continue
        отр, макс, крит = _бал(к, в.get(к["код"]))
        гр = групи.setdefault(г, {"назва": ГРУПИ.get(г, г), "отримано": 0.0, "максимум": 0.0, "критичні": []})
        гр["отримано"] += отр
        гр["максимум"] += макс
        if крит:
            гр["критичні"].append(к["питання"])
            критичні.append({"група": г, "що": к["питання"]})
    # Запізнення понад поріг — критична помилка кур'єра (або точки).
    зап = запізнення_хв(в)
    if зап is not None and зап > налаштування.дай("поріг_запізнення_хв"):
        г = "точка" if п.get("канал") == "Самовивіз" else "курєр"
        гр = групи.setdefault(г, {"назва": ГРУПИ.get(г, г), "отримано": 0.0, "максимум": 0.0, "критичні": []})
        що = f"Запізнення {зап} хв понад поріг"
        гр["критичні"].append(що)
        критичні.append({"група": г, "що": що})

    ваги = налаштування.дай("ваги_груп")
    сума, сума_ваг = 0.0, 0.0
    for г, гр in групи.items():
        if гр["максимум"]:
            гр["відсоток"] = round(100 * гр["отримано"] / гр["максимум"])
        else:
            гр["відсоток"] = None
        if гр["критичні"]:
            гр["відсоток"] = 0          # незалік групи
        gр_зона = зона(гр["відсоток"])
        гр["зона"] = gр_зона
        if гр["відсоток"] is not None:
            w = ваги.get(г, 1)
            сума += гр["відсоток"] * w
            сума_ваг += w
    загальна = round(сума / сума_ваг) if сума_ваг else None
    return {
        "загальна": загальна,
        "зона": зона(загальна),
        "групи": групи,
        "критичні": критичні,
        "час_доставки_хв": час_доставки_хв(в),
        "запізнення_хв": зап,
        "версія_анкети": п.get("анкета", {}).get("версія"),
        "ваги": ваги,
        "пораховано": форма.зараз(),
    }


def червона(о):
    return о.get("зона") == "червона" or bool(о.get("критичні"))
