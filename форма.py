#!/usr/bin/env python3
"""Універсальний покроковий діалог: анкета кандидата, анкета перевірки,
інструктаж — усе це список кроків, який бот проходить із людиною.

Форма не знає про Telegram, бот не знає, які в ній питання. Крок:

    {код, тип, питання, обов=true, підказка, варіанти, кілька,
     група, вага, очікується, бали, критично, нд}

Типи: оцінка (1–5), так_ні, вибір, текст, число, фото, час, контакт,
згода. `нд` — дозволити «не застосовно»: у розрахунку не бере участі.
`кілька` для вибору — можна відмітити кілька варіантів.

Стан кожного чату лежить у ~/.shopper/сесії.json і переживає
перезапуск: тайник може півгодини чекати кур'єра, і втратити внесене
означає, що анкету він кине.
"""
from datetime import datetime

import сховище

ТИПИ = {"оцінка", "так_ні", "вибір", "текст", "число", "фото", "час", "контакт", "згода"}
ФАЙЛ = "сесії.json"
НД = "н/д"


def _сесії():
    return сховище.json_читати(ФАЙЛ, {})


def _зберегти():
    сховище.json_писати(ФАЙЛ, _сесії())


def поточна(chat):
    return _сесії().get(str(chat))


def почати(chat, ключ, кроки, контекст=None, відповіді=None):
    """Нова форма для чату. `ключ` каже боту, що робити з результатом."""
    с = {"ключ": ключ, "кроки": кроки, "крок": 0,
         "відповіді": dict(відповіді or {}), "контекст": контекст or {},
         "почато": datetime.now().isoformat(timespec="seconds")}
    _сесії()[str(chat)] = с
    _зберегти()
    return с


def закрити(chat):
    с = _сесії().pop(str(chat), None)
    _зберегти()
    return с


def крок(с):
    i = с.get("крок", 0)
    return с["кроки"][i] if 0 <= i < len(с["кроки"]) else None


def прогрес(с):
    return с["крок"] + 1, len(с["кроки"])


def обовязковий(к):
    return к.get("обов", True)


def відповісти(chat, значення):
    с = поточна(chat)
    к = крок(с)
    if к is None:
        return None
    с["відповіді"][к["код"]] = значення
    с["крок"] += 1
    _зберегти()
    return крок(с)


def пропустити(chat):
    с = поточна(chat)
    к = крок(с)
    if к is None or обовязковий(к):
        return к
    с["відповіді"].pop(к["код"], None)
    с["крок"] += 1
    _зберегти()
    return крок(с)


def назад(chat):
    с = поточна(chat)
    if с["крок"] > 0:
        с["крок"] -= 1
        _зберегти()
    return крок(с)


def перейти(chat, код):
    с = поточна(chat)
    for i, к in enumerate(с["кроки"]):
        if к["код"] == код:
            с["крок"] = i
            _зберегти()
            return к
    return None


def до_кінця(chat):
    с = поточна(chat)
    с["крок"] = len(с["кроки"])
    _зберегти()


def перемкнути_вибір(chat, варіант):
    """Для вибору з `кілька`: додати або зняти відмітку, не рухаючись далі."""
    с = поточна(chat)
    к = крок(с)
    обрані = list(с["відповіді"].get(к["код"]) or [])
    if варіант in обрані:
        обрані.remove(варіант)
    else:
        обрані.append(варіант)
    с["відповіді"][к["код"]] = обрані
    _зберегти()
    return обрані


def розібрати(к, текст):
    """Текстова відповідь → значення потрібного типу, або None, якщо не підходить."""
    т = к["тип"]
    текст = (текст or "").strip()
    if т == "текст":
        return текст or None
    if т == "число":
        try:
            return float(текст.replace(",", ".").replace(" ", ""))
        except ValueError:
            return None
    if т == "оцінка":
        return int(текст) if текст in ("1", "2", "3", "4", "5") else None
    if т == "так_ні":
        н = текст.lower()
        if н in ("так", "да", "yes", "+", "1"):
            return True
        if н in ("ні", "нет", "no", "-", "0"):
            return False
        return None
    if т == "вибір":
        return текст if текст in к.get("варіанти", []) else None
    if т == "час":
        try:
            г, х = текст.replace(".", ":").split(":")
            return datetime.now().replace(hour=int(г), minute=int(х), second=0, microsecond=0).isoformat(timespec="seconds")
        except (ValueError, AttributeError):
            return None
    if т == "контакт":
        цифри = "".join(ч for ч in текст if ч.isdigit())
        return "+" + цифри if 9 <= len(цифри) <= 13 else None
    return None


def перевірити_кроки(кроки):
    """Помилки формату списку кроків — для selftest."""
    помилки, коди = [], set()
    for к in кроки:
        код = к.get("код")
        if not код:
            помилки.append(f"крок без коду: {к}")
            continue
        if код in коди:
            помилки.append(f"код повторюється: {код}")
        коди.add(код)
        if к.get("тип") not in ТИПИ:
            помилки.append(f"{код}: невідомий тип {к.get('тип')!r}")
        if not к.get("питання"):
            помилки.append(f"{код}: немає питання")
        if к.get("тип") == "вибір" and not к.get("варіанти"):
            помилки.append(f"{код}: вибір без варіантів")
        if к.get("тип") == "вибір" and set(к.get("бали", {})) - set(к.get("варіанти", [])):
            помилки.append(f"{код}: бали для неіснуючих варіантів")
        if к.get("тип") == "так_ні" and к.get("вага") and "очікується" not in к:
            помилки.append(f"{код}: так_ні з вагою без «очікується»")
    return помилки


def зараз():
    return datetime.now().isoformat(timespec="seconds")
