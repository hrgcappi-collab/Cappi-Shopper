#!/usr/bin/env python3
"""Анкета перевірки: з анкета.json і еталонів заказаних позицій збирає
список кроків для форми.

Анкета збирається під завдання: канал визначає блоки, позиції із
завдання — міні-блоки по стравах (питання беруться з ознак еталону),
відповідь про контакт з оператором вмикає блок оператора. Тому список
кроків перераховується після кожної відповіді: `оновити` підміняє
кроки в сесії, не гублячи позицію.

Два етапи: «до» — одразу після оформлення, доки замовлення їде;
«після» — коли отримав. Обидва зберігаються в одній перевірці.
"""
import copy
import json
import os
from datetime import datetime

import форма

ТУТ = os.path.dirname(os.path.abspath(__file__))
_анкета = None
ФАЙЛ_ДАНИХ = "анкета.json"          # правки маркетолога — поверх версії з репозиторію
ФАЙЛ_ВЕРСІЙ = "анкета_версії.json"   # усі колишні версії: перевірка прив'язана до своєї


def анкета():
    """Чинна анкета: правлена маркетологом (~/.shopper/анкета.json), інакше з коду."""
    global _анкета
    if _анкета is None:
        import сховище
        своя = сховище.json_читати(ФАЙЛ_ДАНИХ, None)
        if своя and своя.get("блоки"):
            _анкета = своя
        else:
            with open(os.path.join(ТУТ, "анкета.json"), encoding="utf-8") as f:
                _анкета = json.load(f)
    return _анкета


def версія():
    return анкета()["версія"]


def за_версією(в):
    """Анкета конкретної версії — для перевірок, зданих за старою."""
    import сховище
    if в == версія():
        return анкета()
    return сховище.json_читати(ФАЙЛ_ВЕРСІЙ, {}).get(str(в)) or анкета()


def нова_редакція(нова, хто):
    """Нова редакція від маркетолога: перевіряємо, зберігаємо стару у
    версії, підвищуємо номер версії. Повертає (версія, помилки)."""
    global _анкета
    import сховище
    import журнал
    помилки = _перевірити_структуру(нова)
    if помилки:
        return None, помилки
    стара = анкета()
    версії = сховище.json_читати(ФАЙЛ_ВЕРСІЙ, {})
    версії[str(стара["версія"])] = стара
    сховище.json_писати(ФАЙЛ_ВЕРСІЙ, версії)
    try:
        мажор, мінор = str(стара["версія"]).split(".")[:2]
        нова_версія = f"{мажор}.{int(мінор) + 1}"
    except ValueError:
        нова_версія = str(стара["версія"]) + ".1"
    нова = {"версія": нова_версія, "_": нова.get("_", стара.get("_", "")), "блоки": нова["блоки"],
            "змінено": {"хто": хто, "коли": datetime.now().isoformat(timespec="seconds")}}
    сховище.json_писати(ФАЙЛ_ДАНИХ, нова)
    _анкета = нова
    журнал.запис(хто, "анкета:нова версія", нова_версія, f"блоків {len(нова['блоки'])}, кроків {sum(len(б.get('кроки', [])) for б in нова['блоки'])}")
    return нова_версія, []


def _перевірити_структуру(а):
    if not isinstance(а, dict) or not isinstance(а.get("блоки"), list) or not а["блоки"]:
        return ["потрібен об'єкт з непорожнім списком «блоки»"]
    global _анкета
    збережена = _анкета
    _анкета = {"версія": "?", "блоки": а["блоки"]}
    try:
        return перевірити()
    finally:
        _анкета = збережена


def _умова(коли, п, відповіді):
    if "будь_яке" in коли:
        return any(_умова(у, п, відповіді) for у in коли["будь_яке"])
    if "канал" in коли and п.get("канал") not in коли["канал"]:
        return False
    if "канал_не" in коли and п.get("канал") in коли["канал_не"]:
        return False
    if "провокація" in коли and bool((п.get("завдання") or {}).get("провокація")) != коли["провокація"]:
        return False
    for код, треба in (коли.get("відповідь") or {}).items():
        if відповіді.get(код) != треба:
            return False
    return True


def _підходить(блок, п, відповіді):
    return _умова(блок.get("коли") or {}, п, відповіді)


def _кроки_страв(п):
    """По одному міні-блоку на кожну позицію із завдання — з її еталону."""
    кроки = []
    for поз in п["завдання"].get("позиції", []):
        е = поз.get("еталон") or {}
        пф = f"стр_{поз['id']}"
        назва = поз["назва"]
        for i, ознака in enumerate(е.get("ознаки", [])):
            кроки.append({"код": f"{пф}_озн{i}", "тип": "так_ні", "питання": f"{назва}: {ознака}?",
                          "очікується": True, "вага": 2, "група": "кухня", "позиція": поз["id"], "нд": True})
        if е.get("шматків"):
            кроки.append({"код": f"{пф}_шматків", "тип": "число", "питання": f"{назва}: скільки шматків? (норма {е['шматків']})",
                          "норма": е["шматків"], "вага": 2, "група": "кухня", "позиція": поз["id"]})
        if е.get("фірмове"):
            кроки.append({"код": f"{пф}_фірмове", "тип": "так_ні", "питання": f"{назва}: {е['фірмове']} — так?",
                          "очікується": True, "вага": 1, "група": "кухня", "позиція": поз["id"], "нд": True})
        кроки.append({"код": f"{пф}_фото", "тип": "фото", "питання": f"{назва}: фото без упаковки", "позиція": поз["id"]})
    return кроки


def _питання_допів(база):
    """Апсел конкретний: соус, рол, десерт, напої — плюс чинні акції з сайту (через Loopa)."""
    try:
        import loopa
        акції = [н["назва"] for н in loopa.новинки_акції() if н.get("тип") == "акція"][:3]
    except Exception:
        акції = []
    приклади = "соус до піци, рол, десерт, напій" + (", акції: " + ", ".join(акції) if акції else "")
    return f"{база} ({приклади})"


def кроки(п, етап, відповіді=None):
    відповіді = відповіді or {}
    res = []
    # Здана анкета читається за своєю версією: перейменували питання —
    # старі перевірки не розсипались.
    джерело = за_версією(п.get("анкета", {}).get("версія")) if п.get("анкета", {}).get("версія") else анкета()
    for блок in джерело["блоки"]:
        if блок.get("етап") != етап or not _підходить(блок, п, відповіді):
            continue
        if блок.get("динамічний") == "позиції":
            сирі = _кроки_страв(п)
        else:
            сирі = блок["кроки"]
        for к in сирі:
            if к.get("канали") and п.get("канал") not in к["канали"]:
                continue                        # крок лише для певних каналів
            к = copy.deepcopy(к)
            if к["код"] == "оп_допи":
                к["питання"] = _питання_допів(к["питання"])
            к["блок"] = блок["код"]
            к["блок_назва"] = блок["назва"]
            if блок.get("група") and "група" not in к:
                к["група"] = блок["група"]
            res.append(к)
    return res


def почати(chat, п, етап):
    """Відкриває форму етапу; вже внесене (чернетка) підставляється."""
    внесене = п.get("анкета", {}).get("відповіді", {})
    return форма.почати(chat, f"анкета:{етап}", кроки(п, етап, внесене),
                        контекст={"перевірка": п["id"], "етап": етап}, відповіді=внесене)


def оновити(chat, п, після_коду=None):
    """Перебудувати кроки під свіжі відповіді.

    Позиція — одразу після щойно відповіданого кроку: якщо відповідь
    увімкнула новий блок (оператор), він стане наступним, а не
    проскочить. Без коду — лишаємось на поточному кроці.
    """
    с = форма.поточна(chat)
    if not с or not с["ключ"].startswith("анкета:"):
        return
    орієнтир = після_коду or (форма.крок(с) or {}).get("код")
    зсув = 1 if після_коду else 0
    нові = кроки(п, с["контекст"]["етап"], с["відповіді"])
    с["кроки"] = нові
    for i, к in enumerate(нові):
        if к["код"] == орієнтир:
            с["крок"] = i + зсув
            break
    else:
        с["крок"] = min(с["крок"], len(нові))
    форма._зберегти()


def усі_кроки(п):
    """Повний список кроків обох етапів за фактичними відповідями —
    для оцінки і звіту."""
    в = п.get("анкета", {}).get("відповіді", {})
    return кроки(п, "до", в) + кроки(п, "після", в)


def чого_бракує(п):
    """Обов'язкові кроки без відповіді — для приймання."""
    в = п.get("анкета", {}).get("відповіді", {})
    return [к for к in усі_кроки(п) if форма.обовязковий(к) and в.get(к["код"]) is None]


def перевірити():
    помилки = []
    for блок in анкета()["блоки"]:
        if not блок.get("код") or not блок.get("назва") or блок.get("етап") not in ("до", "після"):
            помилки.append(f"блок без коду/назви/етапу: {блок.get('код')}")
        if блок.get("динамічний"):
            continue
        for п in форма.перевірити_кроки(блок.get("кроки", [])):
            помилки.append(f"{блок.get('код')}: {п}")
    коди = [к["код"] for б in анкета()["блоки"] if not б.get("динамічний") for к in б["кроки"]]
    for к in set(коди):
        if коди.count(к) > 1:
            помилки.append(f"код кроку повторюється між блоками: {к}")
    return помилки
