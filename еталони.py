#!/usr/bin/env python3
"""База еталонів страв — читаємо, не пишемо.

Живе поза ботом (Google Drive → вивантаження у ~/.shopper/еталони.json),
власник — шеф-кухар. Поки справжньої немає, береться зразок із
репозиторію. Правила з ТЗ, які виконує саме цей модуль:

- у завдання і анкету потрапляють лише картки зі статусом
  «опубліковано»: чернетка — ні;
- анкета прив'язується до версії картки на дату замовлення, тому в
  перевірці зберігається копія картки, а не посилання.
"""
import json
import os
from datetime import datetime

import сховище

ТУТ = os.path.dirname(os.path.abspath(__file__))


def база():
    try:
        with open(сховище.шлях("еталони.json"), encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        with open(os.path.join(ТУТ, "еталони.приклад.json"), encoding="utf-8") as f:
            return json.load(f)


def _новинки():
    """Новинки й акції: з Loopa (сайт, щогодини) плюс ручний новинки.json як запасний."""
    import loopa
    return loopa.новинки_акції() + сховище.json_читати("новинки.json", {}).get("записи", [])


def без_картки():
    """Новинки й акції з сайту, на які немає опублікованого еталону —
    генератор їх не призначить, поки шеф не заведе картку."""
    import syrve
    картки = опубліковані()
    res = []
    for н in _новинки():
        if not any((н.get("syrve_id") and н["syrve_id"] in (к.get("syrve_id"), к.get("id"))) or syrve.схоже(н["назва"], к["назва"]) for к in картки):
            res.append(н)
    return res


def опубліковані():
    """Опубліковані картки з ознаками. Якщо позиція є у списку новинок або
    акцій (новинки.json від маркетингу / CappiX) — її категорія стає
    «новинки» чи «акційні», щоб матриця покриття їх бачила, а дата
    запуску — щоб не перевіряти раніше ніж за 7 днів."""
    import syrve
    новинки = _новинки()
    сьогодні = datetime.now().date().isoformat()
    res = []
    for к in база().get("картки", []):
        if к.get("статус") != "опубліковано" or not к.get("ознаки"):
            continue
        к = dict(к)
        for н in новинки:
            if (н.get("syrve_id") and н["syrve_id"] in (к.get("syrve_id"), к.get("id"))) or syrve.схоже(н["назва"], к["назва"]):
                if н.get("до") and н["до"] < сьогодні:
                    continue
                к["категорія"] = "акційні" if н["тип"] == "акція" else "новинки"
                if н.get("від") and not к.get("запущено"):
                    к["запущено"] = н["від"]
        res.append(к)
    return res


def за_id(id_):
    return next((к for к in база().get("картки", []) if к.get("id") == id_), None)


def за_категорією(категорія):
    return [к for к in опубліковані() if к.get("категорія") == категорія]


def категорії_покриті():
    return sorted({к["категорія"] for к in опубліковані()})


# ---------------------------------------------------------------- Syrve
ЗВЯЗКИ = "еталони_звязки.json"


def звязки():
    return сховище.json_читати(ЗВЯЗКИ, {})


def звязати(номенклатура):
    """Картки без syrve_id → товар Syrve за назвою. Повертає (звязано, не знайдено)."""
    import syrve
    зв = звязки()
    знайдено, ні = [], []
    for к in база().get("картки", []):
        if к.get("syrve_id"):
            зв[к["id"]] = {"syrve_id": к["syrve_id"], "назва": к["назва"]}
            continue
        товар = next((т for т in номенклатура if т.get("назва") and syrve.схоже(к["назва"], т["назва"])), None)
        if товар:
            зв[к["id"]] = {"syrve_id": товар["id"], "назва": товар["назва"], "ціна": товар.get("ціна")}
            знайдено.append((к["назва"], товар["назва"]))
        else:
            ні.append(к["назва"])
    сховище.json_писати(ЗВЯЗКИ, зв)
    return знайдено, ні


def syrve_id(картка):
    return картка.get("syrve_id") or (звязки().get(картка["id"]) or {}).get("syrve_id")


def перевірити():
    """Помилки формату — для selftest і для екрану маркетолога."""
    помилки = []
    б = база()
    ids = set()
    for к in б.get("картки", []):
        if not к.get("id") or not к.get("назва"):
            помилки.append(f"картка без id або назви: {к}")
            continue
        if к["id"] in ids:
            помилки.append(f"id повторюється: {к['id']}")
        ids.add(к["id"])
        if к.get("статус") == "опубліковано" and not к.get("ознаки"):
            помилки.append(f"{к['назва']}: опубліковано без ознак")
        if к.get("статус") == "опубліковано" and not к.get("категорія"):
            помилки.append(f"{к['назва']}: без категорії")
    return помилки


# ---------------------------------------------------------------- фото
ФОТО = "еталони_фото.json"
ВИДИ_ФОТО = {"упаковка": "В упаковці", "без": "Без упаковки", "розріз": "У розрізі"}


def фото(картка_id=None):
    ф = сховище.json_читати(ФОТО, {})
    return ф.get(картка_id, {}) if картка_id else ф


def додати_фото(підпис, file_id, file_unique_id=None):
    """Підпис: «еталон Філадельфія розріз». Повертає (картка, вид) або (None, причина)."""
    import syrve
    слова = підпис.strip().split()
    if not слова or слова[0].lower() not in ("еталон", "етaлон", "эталон"):
        return None, "підпис має починатись зі слова «еталон»"
    вид = "без"
    if len(слова) > 2 and слова[-1].lower() in ВИДИ_ФОТО:
        вид = слова[-1].lower()
        назва = " ".join(слова[1:-1])
    else:
        назва = " ".join(слова[1:])
    картка = next((к for к in база().get("картки", []) if syrve.схоже(назва, к["назва"])), None)
    if not картка:
        return None, f"картки «{назва}» немає в базі еталонів"
    ф = сховище.json_читати(ФОТО, {})
    ф.setdefault(картка["id"], {})[вид] = {"file_id": file_id, "unique": file_unique_id, "коли": datetime.now().isoformat(timespec="seconds")}
    сховище.json_писати(ФОТО, ф)
    return картка, вид
