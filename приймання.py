#!/usr/bin/env python3
"""Приймання анкети агентом — ТЗ розділ 13.

Чек-лист автоперевірок фіксований, інакше «агент приймає» означає
«ніхто не приймає». На етапі 1 звірки з Syrve немає — вона позначається
«відкладено», і рішення ухвалює маркетолог. Агент готує рекомендацію
з причинами; людина погоджується одним натисканням або вирішує інакше.

Результати:
    на доробці   бракує обов'язкового — агент повертає сам, зі списком
    на ревю      усе є, але є сумніви або просто треба око людини
Відхилити може лише маркетолог, з підставою.
"""
from datetime import datetime, timedelta

import анкета
import журнал
import налаштування
import перевірки
import syrve
import тайники
import форма


def _фото_дублікати(п):
    """Той самий file_unique_id у минулих анкетах — фото з іншої перевірки."""
    свої = set((п.get("анкета", {}).get("фото_унікальні") or {}).values())
    if not свої:
        return []
    for інша in перевірки.усі():
        if інша["id"] == п["id"]:
            continue
        чужі = set((інша.get("анкета", {}).get("фото_унікальні") or {}).values())
        if свої & чужі:
            return sorted(свої & чужі)
    return []


def _суперечності(в):
    res = []
    заг = в.get("заг_оцінка")
    if в.get("кух_температура") == "Холодна" and (в.get("кух_смак") or 0) >= 4:
        res.append("температура «холодна», а смак 4–5")
    if в.get("кух_склад") is False and (заг or 0) >= 4:
        res.append("привезли не те, а загальна оцінка 4–5")
    if в.get("уп_протікання") is True and (в.get("уп_цілісність") or 0) >= 4:
        res.append("протекло, а цілісність упаковки 4–5")
    if в.get("кух_сторонній") is True and (заг or 0) >= 3:
        res.append("сторонній предмет, а загальна оцінка 3+")
    return res


def _односкладові(в):
    return [код for код in ("заг_враження", "кух_коментар") if в.get(код) and len(str(в[код]).strip()) < 15 and код == "заг_враження"]


def _скопійовано(п):
    """Той самий текст враження у минулій анкеті цього ж тайника."""
    в = п["анкета"]["відповіді"]
    т = (в.get("заг_враження") or "").strip().lower()
    if not т:
        return False
    for інша in перевірки.історія_тайника(п["тайник"]):
        if інша["id"] != п["id"] and (інша.get("анкета", {}).get("відповіді", {}).get("заг_враження") or "").strip().lower() == т:
            return True
    return False


def _однакові_оцінки(п):
    """Тайник систематично ставить одну й ту саму оцінку."""
    оцінки = [v for k in анкета.усі_кроки(п) if k["тип"] == "оцінка"
              for v in [п["анкета"]["відповіді"].get(k["код"])] if isinstance(v, int)]
    return len(оцінки) >= 8 and len(set(оцінки)) == 1


def _після_дедлайну(п):
    здано = п["анкета"].get("здано")
    отримано = п["анкета"]["відповіді"].get("час_отримання")
    if not здано or not отримано:
        return False
    try:
        return datetime.fromisoformat(здано) > datetime.fromisoformat(отримано) + timedelta(hours=п["завдання"]["дедлайн_анкети_годин"])
    except (ValueError, KeyError, TypeError):
        return False


def _вікно_дотримано(п):
    оф = п["анкета"]["відповіді"].get("час_оформлення")
    if not оф:
        return None
    в = п["вікно"]
    try:
        t = datetime.fromisoformat(оф)
        return t.date().isoformat() == в["дата"] and в["від"] <= t.strftime("%H:%M") <= в["до"]
    except ValueError:
        return None


def _сума_в_ліміті(п):
    с = п["анкета"]["відповіді"].get("сума_замовлення")
    return None if с is None else float(с) <= п["завдання"]["бюджет"]


def _звірка_syrve(п):
    """Факт замовлення проти анкети і завдання. Недоступний Syrve — не
    провал, а «відкладено»: планувальник повторить."""
    if not syrve.налаштовано():
        return ("Звірка з Syrve", None, "не налаштовано")
    т = тайники.картка(п["тайник"]) or {}
    if not т.get("телефон"):
        return ("Звірка з Syrve", None, "у тайника немає телефону")
    try:
        с = syrve.звірити(п, т["телефон"])
    except syrve.Недоступний as e:
        п["syrve_відкладено"] = True
        перевірки.зберегти(п)
        return ("Звірка з Syrve", None, f"відкладено: {e}")
    п["syrve"] = с
    п.pop("syrve_відкладено", None)
    перевірки.зберегти(п)
    if not с["знайдено"]:
        return ("Звірка з Syrve", False, "замовлення з номера тайника не знайдено")
    провалені = [н for н, ок in с["збіги"].items() if ок is False]
    return ("Звірка з Syrve", not провалені, "; ".join(провалені))


def перевірити(п):
    """Запускає чек-лист і повертає результат; статус міняє `провести`."""
    в = п["анкета"]["відповіді"]
    бракує = анкета.чого_бракує(п)
    перевірки_ = []          # (назва, пройдено: True/False/None, деталь)
    перевірки_.append(("Повнота: усі обов'язкові поля і фото", not бракує, ", ".join(к["питання"][:40] for к in бракує[:5])))
    дубл = _фото_дублікати(п)
    перевірки_.append(("Фото не з минулих анкет", not дубл, f"{len(дубл)} збігів" if дубл else ""))
    супер = _суперечності(в)
    перевірки_.append(("Без внутрішніх суперечностей", not супер, "; ".join(супер)))
    перевірки_.append(("Коментарі змістовні", not _односкладові(в) and not _скопійовано(п),
                       "односкладове або скопійоване враження" if (_односкладові(в) or _скопійовано(п)) else ""))
    перевірки_.append(("Оцінки не під копірку", not _однакові_оцінки(п), "усі оцінки однакові" if _однакові_оцінки(п) else ""))
    вікно = _вікно_дотримано(п)
    перевірки_.append(("Оформлено у вікно завдання", вікно, "" if вікно else "час оформлення поза вікном"))
    ліміт = _сума_в_ліміті(п)
    перевірки_.append(("Сума в ліміті бюджету", ліміт, "" if ліміт else f"{в.get('сума_замовлення')} > {п['завдання']['бюджет']}"))
    перевірки_.append(("Анкета здана вчасно", not _після_дедлайну(п), "після дедлайну — виплата є, рейтинг нижче" if _після_дедлайну(п) else ""))
    перевірки_.append(_звірка_syrve(п))

    непройдено = [н for н, ок, _ in перевірки_ if ок is False]
    if бракує:
        рекомендація, чому = "на доробку", f"бракує {len(бракує)} обов'язкових відповідей"
    elif len(непройдено) >= налаштування.дай("поріг_ревю"):
        рекомендація, чому = "розібрати", "не пройдено: " + "; ".join(непройдено)
    elif непройдено:
        рекомендація, чому = "прийняти з приміткою", "не пройдено: " + "; ".join(непройдено)
    else:
        рекомендація, чому = "прийняти", "усі автоперевірки пройдено" + ("" if п.get("syrve") else ", звірка з Syrve відкладена")
    return {"коли": форма.зараз(), "перевірки": [{"що": н, "ок": ок, "деталь": д} for н, ок, д in перевірки_],
            "бракує": [к["код"] for к in бракує], "рекомендація": рекомендація, "чому": чому}


def провести(п):
    """Автоприймання після здачі: або повертає на доробку, або на ревю."""
    р = перевірити(п)
    п["приймання"] = р
    перевірки.зберегти(п)
    if р["бракує"]:
        п["доробка_до"] = (datetime.now() + timedelta(hours=налаштування.дай("доробка_годин"))).isoformat(timespec="seconds")
        перевірки.статус(п, "на доробці", "агент", р["чому"])
    else:
        import мозок
        import оцінка as _оцінка
        п["оцінка"] = _оцінка.порахувати(п)          # попередня — для картки і пропозиції
        р["пропозиція"] = мозок.пропозиція(п)
        п["приймання"] = р
        перевірки.статус(п, "на ревю", "агент", f"рекомендація: {р['рекомендація']} — {р['чому']}")
    return р


def бал_якості_анкети(п):
    """1–5: повнота, фото, змістовність, строки, автоперевірки. Іде в рейтинг."""
    р = п.get("приймання") or перевірити(п)
    пройдено = sum(1 for x in р["перевірки"] if x["ок"] is True)
    усього = sum(1 for x in р["перевірки"] if x["ок"] is not None)
    в = п["анкета"]["відповіді"]
    змістовно = len((в.get("заг_враження") or "")) >= 60
    бал = 1 + 3 * (пройдено / усього if усього else 0) + (1 if змістовно else 0)
    return round(min(5, бал), 1)


def текст(п):
    р = п.get("приймання")
    if not р:
        return "автоперевірок ще не було"
    значки = {True: "✅", False: "❌", None: "⏸"}
    рядки = [f"{значки[x['ок']]} {x['що']}" + (f" — {x['деталь']}" if x["деталь"] else "") for x in р["перевірки"]]
    рядки.append("")
    рядки.append(f"🤖 Рекомендація агента: <b>{р['рекомендація']}</b> — {р['чому']}")
    if р.get("пропозиція"):
        import html
        рядки.append(html.escape(р["пропозиція"], quote=False))
    return "\n".join(рядки)
