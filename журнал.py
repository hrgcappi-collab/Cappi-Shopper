#!/usr/bin/env python3
"""Журнал рішень агента і дій людей.

ТЗ: «кожне рішення агента супроводжується записом обґрунтування: що
перевірено, які розбіжності знайдені, чому прийнято саме це рішення.
Без журналу спір по анкеті нерозв'язний». Тому пишемо не лише що
сталося, а й чому — окремим полем, людською мовою.
"""
from datetime import datetime

import сховище

ФАЙЛ = "журнал.jsonl"
АГЕНТ = "агент"


def запис(хто, дія, обєкт, чому=""):
    з = {"коли": datetime.now().isoformat(timespec="seconds"),
         "хто": хто, "дія": дія, "обєкт": str(обєкт), "чому": чому}
    сховище.jsonl_дописати(ФАЙЛ, з)
    return з


def по_обєкту(обєкт):
    return [з for з in сховище.jsonl_читати(ФАЙЛ) if з["обєкт"] == str(обєкт)]


def останні(скільки=30, хто=None):
    всі = сховище.jsonl_читати(ФАЙЛ)
    if хто:
        всі = [з for з in всі if з["хто"] == хто]
    return всі[-скільки:]


def за_період(від, до=None):
    return [з for з in сховище.jsonl_читати(ФАЙЛ)
            if з["коли"] >= від and (до is None or з["коли"] < до)]
