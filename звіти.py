#!/usr/bin/env python3
"""Тексти: картка перевірки для маркетолога, звіти в робочі чати,
дайджести. Сюди — все, що бот пише людям про результати.

ТЗ розділ 15: кожен чат отримує лише свою зону відповідальності;
ім'я, телефон і Telegram тайника в робочі чати не потрапляють ні за
яких умов — лише номер перевірки і знеособлений Т-012. Червона зона —
негайно, решта — тижневою зводкою.
"""
import html
from datetime import datetime, timedelta

import анкета
import оцінка
import перевірки
import syrve
import тайники
import форма

ЗІРКИ = {5: "★★★★★", 4: "★★★★☆", 3: "★★★☆☆", 2: "★★☆☆☆", 1: "★☆☆☆☆"}
ЗНАЧОК_ЗОНИ = {"зелена": "🟢", "жовта": "🟡", "червона": "🔴", None: "⚪"}

# Який чат які групи бачить. Кухня — по своїй філії.
АДРЕСАТИ = {
    "кухня_Лазарєва": {"групи": ["кухня", "упаковка"], "філія": "Лазарєва", "фото": True},
    "кухня_Левітана": {"групи": ["кухня", "упаковка"], "філія": "Левітана", "фото": True},
    "курєри": {"групи": ["курєр", "точка"], "тайминг": True},
    "оператори": {"групи": ["оператор"]},
    "керівництво": {"групи": ["кухня", "упаковка", "курєр", "точка", "оператор", "сайт"], "тайминг": True},
}


def е(т):
    return html.escape(str(т if т is not None else ""), quote=False)


def показати(к, в):
    т = к["тип"]
    if в is None:
        return "—"
    if в == форма.НД:
        return "н/д"
    if т == "оцінка":
        return ЗІРКИ.get(в, str(в))
    if т == "так_ні":
        return "так" if в else "ні"
    if т == "час":
        try:
            return datetime.fromisoformat(в).strftime("%H:%M")
        except ValueError:
            return е(в)
    if т == "число":
        return str(int(в)) if float(в).is_integer() else str(в)
    if т == "фото":
        return "📷"
    if isinstance(в, list):
        return ", ".join(е(x) for x in в)
    return е(в)


def шапка(п):
    о = п.get("оцінка") or {}
    return (f"{ЗНАЧОК_ЗОНИ.get(о.get('зона'))} <b>Перевірка {п['id']}</b> · {е(п['філія'])} · {е(п['канал'])} · {п['вікно']['дата']}")


def рядок_груп(о, групи=None):
    рядки = []
    for г, гр in (о.get("групи") or {}).items():
        if групи and г not in групи:
            continue
        if гр.get("відсоток") is None:
            continue
        крит = " ❗ " + "; ".join(гр["критичні"]) if гр.get("критичні") else ""
        рядки.append(f"  {ЗНАЧОК_ЗОНИ.get(гр.get('зона'))} {е(гр['назва'])}: <b>{гр['відсоток']}%</b>{крит}")
    return рядки


def тайминг(п):
    о = п.get("оцінка") or {}
    в = п["анкета"]["відповіді"]
    if о.get("час_доставки_хв") is None:
        return None
    т = f"⏱ Доставка: <b>{о['час_доставки_хв']} хв</b>" + (" (Syrve)" if о.get("джерело_таймингу") == "Syrve" else "")
    обіц = ((п.get("syrve") or {}).get("замовлення") or {}).get("обіцяно_хв") or в.get("обіцяний_час")
    if обіц:
        т += f", обіцяли {int(обіц)}"
        з = о.get("запізнення_хв")
        if з is not None and з > 0:
            т += f" — <b>запізнення {з} хв</b>"
        elif з is not None:
            т += " — вчасно"
    return т


def підсумок_для_тайника(п, етап):
    """Що людина бачить перед здачею етапу — усе, що внесла."""
    в = п["анкета"]["відповіді"]
    рядки = [f"<b>{п['id']}</b> · {е(п['філія'])} · {е(п['канал'])}", ""]
    останній = None
    for к in анкета.кроки(п, етап, в):
        if к["блок"] != останній:
            рядки.append(f"<b>{е(к['блок_назва'])}</b>")
            останній = к["блок"]
        рядки.append(f"  {е(к['питання'][:60])}: {показати(к, в.get(к['код']))}")
    return "\n".join(рядки)


def картка_маркетолога(п):
    """Повна картка: оцінка, автоперевірки, відповіді. Тайник — під номером."""
    import приймання
    о = п.get("оцінка") or оцінка.порахувати(п)
    в = п["анкета"]["відповіді"]
    рядки = [шапка(п), f"Тайник {тайники.номер(п['тайник'])} · статус: <b>{е(п['статус'])}</b>", ""]
    if о.get("загальна") is not None:
        рядки.append(f"Загальна: <b>{о['загальна']}%</b> ({о.get('зона')})")
    рядки += рядок_груп(о)
    т = тайминг(п)
    if т:
        рядки.append(т)
    if в.get("сума_замовлення"):
        рядки.append(f"Чек за анкетою: {int(в['сума_замовлення'])} грн (ліміт {п['завдання']['бюджет']})")
    рядки += syrve.текст(п.get("syrve"))
    import імпорт
    зміна = імпорт.на_зміні(п["вікно"]["дата"], п["філія"])
    зз = (п.get("syrve") or {}).get("замовлення") or {}
    хто = [f"{x['роль']} {x['імя']}".strip() for x in зміна] + [f"оператор {зз['оператор']}" for _ in [0] if зз.get("оператор")] + [f"кур'єр {зз['курєр']}" for _ in [0] if зз.get("курєр")]
    if хто:
        рядки.append("👤 На зміні (лише для маркетолога): " + е(", ".join(хто)))
    пров = (п.get("завдання") or {}).get("провокація")
    if пров:
        import провокації
        рядки.append(f"🎭 Провокація ({пров['адресат']}): {е(пров['дія'][:70])}"
                     + (" · <i>повтор по співробітнику за квартал — не для кадрових рішень</i>" if провокації.повтор_по_співробітнику(п) else ""))
    рядки += ["", "<b>Автоперевірки</b>", приймання.текст(п), ""]
    if в.get("заг_враження"):
        рядки.append(f"💬 {е(в['заг_враження'])}")
    if в.get("заг_виправити"):
        рядки.append(f"🔧 {е(в['заг_виправити'])}")
    return "\n".join(рядки)


def відповіді_повністю(п):
    в = п["анкета"]["відповіді"]
    рядки = [f"<b>Анкета {п['id']} — усі відповіді</b>"]
    останній = None
    for к in анкета.усі_кроки(п):
        if к["тип"] == "фото":
            continue
        if к["блок"] != останній:
            рядки.append(f"\n<i>{е(к['блок_назва'])}</i>")
            останній = к["блок"]
        рядки.append(f"  {е(к['питання'][:70])}: {показати(к, в.get(к['код']))}")
    return "\n".join(рядки)


def фото(п, лише_позиції=False):
    """(підпис, file_id) усіх фото анкети."""
    в = п["анкета"]["відповіді"]
    res = []
    for к in анкета.усі_кроки(п):
        if к["тип"] == "фото" and в.get(к["код"]) and (not лише_позиції or к.get("позиція") or к["код"] in ("фото_упаковка", "фото_без_упаковки", "фото_розріз")):
            res.append((к["питання"], в[к["код"]]))
    return res


def звіт_у_чат(п, назва_чату, підсумок_ші=None):
    """Картка для робочого чату: лише групи цього чату, без персоналій."""
    а = АДРЕСАТИ.get(назва_чату)
    if not а:
        return None
    if а.get("філія") and п["філія"] != а["філія"]:
        return None
    о = п.get("оцінка") or {}
    групи = рядок_груп(о, а["групи"])
    if not групи:
        return None
    рядки = [шапка(п), ""] + групи
    if а.get("тайминг"):
        т = тайминг(п)
        if т:
            рядки.append(т)
    в = п["анкета"]["відповіді"]
    if "кухня" in а["групи"] and в.get("кух_коментар"):
        рядки.append(f"💬 {е(в['кух_коментар'])}")
    if підсумок_ші:
        рядки += ["", е(підсумок_ші)]
    if "керівництво" == назва_чату and в.get("заг_враження"):
        рядки += ["", f"💬 {е(в['заг_враження'])}"]
    return "\n".join(рядки)


def чати_для(п):
    """Які робочі чати мають отримати цю перевірку."""
    res = []
    for назва, а in АДРЕСАТИ.items():
        if а.get("філія") and п["філія"] != а["філія"]:
            continue
        res.append(назва)
    return res


def тижневий_дайджест(до=None):
    до = до or datetime.now()
    від = (до - timedelta(days=7)).date().isoformat()
    # За датою здачі анкети, не за вікном: прийняте цього тижня — це і є тиждень.
    пп = [п for п in перевірки.усі() if п.get("оцінка") and п["статус"] in ("прийнята", "закрита")
          and від <= (п["анкета"].get("здано") or "")[:10] <= до.date().isoformat()]
    if not пп:
        return f"📊 Тиждень з {від}: прийнятих перевірок не було."
    рядки = [f"📊 <b>Тайний гість · тиждень з {від}</b>", f"Перевірок: {len(пп)}", ""]
    по_філії = {}
    for п in пп:
        по_філії.setdefault(п["філія"], []).append(п)
    for ф, список in по_філії.items():
        серед = round(sum(п["оцінка"]["загальна"] or 0 for п in список) / len(список))
        рядки.append(f"<b>{е(ф)}</b>: {серед}% ({len(список)} перевірок)")
        for п in список:
            рядки.append(f"  {шапка(п).replace('<b>', '').replace('</b>', '')}: {п['оцінка']['загальна']}%")
    червоні = [п for п in пп if оцінка.червона(п["оцінка"])]
    if червоні:
        рядки += ["", "🔴 Червона зона: " + ", ".join(п["id"] for п in червоні)]
    return "\n".join(рядки)


def дайджест_маркетолога(днів=7):
    """Контроль якості самого агента — ТЗ розділ 2."""
    import журнал
    від = (datetime.now() - timedelta(days=днів)).isoformat(timespec="seconds")
    з = журнал.за_період(від)
    агент = [x for x in з if x["хто"] == "агент"]
    лічи = {}
    for x in агент:
        лічи[x["дія"]] = лічи.get(x["дія"], 0) + 1
    рядки = [f"🤖 <b>Що агент зробив сам за {днів} дн.</b>"]
    for д, n in sorted(лічи.items()):
        рядки.append(f"  {е(д)}: {n}")
    прийняті = [п for п in перевірки.усі() if п["статус"] in ("прийнята", "закрита") and п.get("анкета", {}).get("здано", "") >= від]
    if прийняті:
        import random
        вибірка = random.sample(прийняті, min(2, len(прийняті)))
        рядки += ["", "На ручну перевірку (випадково): " + ", ".join(п["id"] for п in вибірка)]
    return "\n".join(рядки)


def місячна_зводка(місяць=None):
    """Динаміка і порівняння філій — ТЗ розділ 15. `місяць` — 'YYYY-MM'."""
    м = місяць or (datetime.now().replace(day=1) - timedelta(days=1)).strftime("%Y-%m")
    поперед = (datetime.fromisoformat(м + "-01") - timedelta(days=1)).strftime("%Y-%m")

    def за(місяць_):
        return [п for п in перевірки.усі() if п.get("оцінка") and п["статус"] in ("прийнята", "закрита")
                and (п["анкета"].get("здано") or "")[:7] == місяць_]

    пп, пп0 = за(м), за(поперед)
    if not пп:
        return f"📈 {м}: прийнятих перевірок не було."

    def середнє(список, група=None):
        зн = [п["оцінка"]["загальна"] if група is None else (п["оцінка"]["групи"].get(група) or {}).get("відсоток")
              for п in список]
        зн = [x for x in зн if x is not None]
        return round(sum(зн) / len(зн)) if зн else None

    def дельта(а, б):
        return "" if а is None or б is None else f" ({'+' if а - б >= 0 else ''}{а - б})"

    рядки = [f"📈 <b>Тайний гість · {м}</b> · перевірок {len(пп)} (минулого місяця {len(пп0)})",
             f"Загальна: <b>{середнє(пп)}%</b>{дельта(середнє(пп), середнє(пп0))}", ""]
    for ф in sorted({п["філія"] for п in пп}):
        свої, свої0 = [п for п in пп if п["філія"] == ф], [п for п in пп0 if п["філія"] == ф]
        рядки.append(f"<b>{е(ф)}</b>: {середнє(свої)}%{дельта(середнє(свої), середнє(свої0))} · {len(свої)} пер.")
        for г in ("кухня", "упаковка", "курєр", "точка", "оператор", "сайт"):
            с = середнє(свої, г)
            if с is not None:
                рядки.append(f"  {е(оцінка.ГРУПИ[г])}: {с}%{дельта(с, середнє(свої0, г))}")
    червоні = [п for п in пп if оцінка.червона(п["оцінка"])]
    if червоні:
        рядки += ["", f"🔴 Червона зона: {len(червоні)} — " + ", ".join(п["id"] for п in червоні)]
    зап = [п["оцінка"]["запізнення_хв"] for п in пп if п["оцінка"].get("запізнення_хв") is not None]
    if зап:
        рядки.append(f"⏱ Обіцяно/факт: середнє відхилення {round(sum(зап) / len(зап))} хв, запізнень понад поріг {sum(1 for x in зап if x > 0)}")
    import виплати
    б = виплати.бюджет_місяця()
    рядки.append(f"💸 Бюджет {б['місяць']}: {б['витрачено']} грн, середня анкета {б['середня']}")
    return "\n".join(рядки)


def для_core(місяць=None):
    """Середня оцінка місяця — у файл, який Core може читати замість ручного
    вводу показника «тайний гість»."""
    import сховище
    м = місяць or datetime.now().strftime("%Y-%m")
    пп = [п for п in перевірки.усі() if п.get("оцінка") and п["статус"] in ("прийнята", "закрита")
          and (п["анкета"].get("здано") or "")[:7] == м and п["оцінка"]["загальна"] is not None]
    д = сховище.json_читати("для_core.json", {})
    if пп:
        д[м] = {"оцінка": round(sum(п["оцінка"]["загальна"] for п in пп) / len(пп)), "перевірок": len(пп),
                "по_філіях": {ф: round(sum(п["оцінка"]["загальна"] for п in пп if п["філія"] == ф) / max(1, sum(1 for п in пп if п["філія"] == ф)))
                              for ф in {п["філія"] for п in пп}},
                "оновлено": datetime.now().isoformat(timespec="seconds")}
        сховище.json_писати("для_core.json", д)
    return д.get(м)


def реєстр_виплат_csv():
    """Реєстр виплат для закриття місяця — CSV, без персоналій."""
    import csv
    import io
    import виплати
    буфер = io.StringIO()
    w = csv.writer(буфер, delimiter=";")
    w.writerow(["заявка", "перевірка", "тайник", "філія", "канал", "дата", "чек", "джерело", "компенсація", "ставка", "разом", "статус", "створено", "виплачено"])
    for п in виплати.реєстр():
        в = п["виплата"]
        w.writerow([в["номер"], п["id"], тайники.номер(п["тайник"]), п["філія"], п["канал"], п["вікно"]["дата"],
                    f"{в['чек']:.0f}", в.get("джерело_чека", ""), в["компенсація"], в["ставка"], в["разом"], в["статус"],
                    в["створено"][:16], (в.get("виплачено") or "")[:16]])
    return буфер.getvalue().encode("utf-8-sig")


def знеособити_старі(днів):
    """Фото і персоналії з анкет старших за N днів стираються; оцінки лишаються."""
    import анкета as _анкета
    межа = (datetime.now() - timedelta(days=днів)).isoformat()
    скільки = 0
    for п in перевірки.усі():
        if п.get("знеособлено") or п["статус"] not in ("закрита", "відхилена", "зрив", "прийнята"):
            continue
        if (п.get("анкета", {}).get("здано") or п["створено"]) >= межа:
            continue
        в = п["анкета"]["відповіді"]
        for к in _анкета.усі_кроки(п):
            if к["тип"] == "фото" and к["код"] in в:
                в[к["код"]] = "знеособлено"
        п["анкета"].pop("фото_унікальні", None)
        for ключ in ("оператор", "курєр", "адреса_хеш"):
            ((п.get("syrve") or {}).get("замовлення") or {}).pop(ключ, None)
        п["знеособлено"] = datetime.now().isoformat(timespec="seconds")
        перевірки.зберегти(п)
        скільки += 1
    return скільки
