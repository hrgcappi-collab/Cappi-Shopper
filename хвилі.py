#!/usr/bin/env python3
"""Хвилі та слоти — ТЗ розділи 4, 6, 8.

Хвиля — тижневий набір на N слотів (типово два). Слот прив'язаний до
дати, вікна часу, філії і каналу; параметри підбирає генератор за
матрицею покриття (завдання.py). Статуси хвилі:
    чернетка → відкрито набір → набір закрито → в виконанні → закрита.

Набір: бот публікує запрошення, перші N, хто відгукнувся і пройшов
кулдаун, займають слоти. Решті пропонуються слоти майбутніх тижнів —
людина не отримує відмову, а бронює дату наперед. Резерв: при зриві
слот переходить першому в черзі.

Дата і вікно слота — від «пік/непік» і «будні/вихідні» зрізу.
"""
from datetime import datetime, timedelta

import журнал
import налаштування
import перевірки
import сховище
import тайники

ФАЙЛ = "хвилі.json"
СТАТУСИ = ["чернетка", "відкрито набір", "набір закрито", "в виконанні", "закрита"]


def _всі():
    return сховище.json_читати(ФАЙЛ, {})


def _зберегти():
    сховище.json_писати(ФАЙЛ, _всі())


def дай(id_):
    return _всі().get(id_)


def усі(статус=None):
    return sorted((х for х in _всі().values() if статус is None or х["статус"] == статус), key=lambda х: х["id"])


def відкрита():
    return next((х for х in усі("відкрито набір")), None)


def _номер():
    л = сховище.json_читати("лічильники.json", {})
    л["хвиля"] = л.get("хвиля", 0) + 1
    сховище.json_писати("лічильники.json", л)
    return f"Х-{л['хвиля']:03d}"


def створити(слоти, хто="агент", тиждень=None):
    """Хвиля із готовим списком слотів (їх підбирає завдання.план_хвилі)."""
    х = {"id": _номер(), "статус": "чернетка", "тиждень": тиждень,
         "створено": datetime.now().isoformat(timespec="seconds"),
         "слоти": [], "черга": [], "відгуки": []}
    for i, с in enumerate(слоти, 1):
        с = dict(с, id=f"{х['id']}/{i}", тайник=None, перевірка=None)
        х["слоти"].append(с)
    _всі()[х["id"]] = х
    _зберегти()
    журнал.запис(хто, "хвиля:чернетка", х["id"], f"{len(слоти)} слотів: " + "; ".join(f"{с['дата']} {с['від']}–{с['до']} {с['філія']} {с['канал']}" for с in слоти))
    return х


def відкрити(х, хто="агент"):
    х["статус"] = "відкрито набір"
    х["відкрито"] = datetime.now().isoformat(timespec="seconds")
    _зберегти()
    журнал.запис(хто, "хвиля:відкрито", х["id"], "запрошення розіслано")
    return х


def вільні_слоти(х):
    return [с for с in х["слоти"] if not с["тайник"]]


def відгукнутись(х, uid):
    """Повертає (слот або None, причина).

    Слот дається, якщо людина готова до завдань, не в кулдауні на дату
    слота і не має активної перевірки. Інакше — в чергу.
    """
    if uid in х["відгуки"]:
        return None, "вже відгукнувся"
    х["відгуки"].append(uid)
    т = тайники.картка(uid)
    if not тайники.готовий_до_завдань(uid):
        _зберегти()
        return None, "не готовий: " + str(тайники.чого_бракує(uid))
    if перевірки.тайника(uid):
        _зберегти()
        return None, "вже є активна перевірка"
    for с in вільні_слоти(х):
        if тайники.у_кулдауні(uid, с["дата"]):
            continue
        с["тайник"] = uid
        _зберегти()
        журнал.запис("агент", "слот:зайнято", с["id"], f"{т['номер']} відгукнувся, кулдаун пройдено")
        if not вільні_слоти(х):
            закрити_набір(х)
        return с, "слот"
    if uid not in х["черга"]:
        х["черга"].append(uid)
    _зберегти()
    причина = "кулдаун" if any(тайники.у_кулдауні(uid, с["дата"]) for с in х["слоти"]) else "слоти зайняті"
    журнал.запис("агент", "черга", х["id"], f"{т['номер']}: {причина}")
    return None, причина


def закрити_набір(х, хто="агент"):
    if х["статус"] == "відкрито набір":
        х["статус"] = "набір закрито"
        _зберегти()
        журнал.запис(хто, "хвиля:набір закрито", х["id"], "усі слоти зайняті")


def звільнити_слот(х, слот_id, хто="агент", чому=""):
    """Зрив або відмова: слот іде першому в черзі, хто проходить кулдаун."""
    с = next(s for s in х["слоти"] if s["id"] == слот_id)
    був = с["тайник"]
    с["тайник"], с["перевірка"] = None, None
    журнал.запис(хто, "слот:звільнено", слот_id, чому or f"{тайники.номер(був)} вибув")
    х["черга"] = тайники.за_рейтингом(х["черга"])
    while х["черга"]:
        uid = х["черга"].pop(0)
        if тайники.готовий_до_завдань(uid) and not тайники.у_кулдауні(uid, с["дата"]) and not перевірки.тайника(uid):
            с["тайник"] = uid
            журнал.запис("агент", "слот:зайнято", слот_id, f"{тайники.номер(uid)} з черги (резерв)")
            break
    if х["статус"] == "набір закрито" and вільні_слоти(х):
        х["статус"] = "відкрито набір"
    _зберегти()
    return с


def привязати_перевірку(х, слот_id, перевірка_id):
    с = next(s for s in х["слоти"] if s["id"] == слот_id)
    с["перевірка"] = перевірка_id
    _зберегти()


def закрити(х, хто="агент"):
    х["статус"] = "закрита"
    _зберегти()
    журнал.запис(хто, "хвиля:закрита", х["id"])


def наступний_тиждень():
    """Понеділок наступного тижня — база для дат слотів."""
    сьогодні = datetime.now().date()
    return сьогодні + timedelta(days=(7 - сьогодні.weekday()))
