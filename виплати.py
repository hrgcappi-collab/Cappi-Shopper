#!/usr/bin/env python3
"""Виплати — ТЗ розділ 16. Гроші переказує адміністратор; бот формує
заявку, веде статуси і закриває цикл підтвердженням отримання.

    очікує приймання → погоджена → у черзі на виплату → виплачена →
    підтверджена отримувачем.   Глухі кути: відхилена, спірна.

Сума = чек (на етапі 1 — з анкети, з етапу 2 — із Syrve), обмежений
лімітом, плюс ставка за анкету. Реквізити зберігаються у картці
тайника і в чати не потрапляють.
"""
from datetime import datetime

import журнал
import налаштування
import перевірки
import тайники

СТАТУСИ = ["очікує приймання", "погоджена", "у черзі на виплату", "виплачена", "підтверджена", "відхилена", "спірна"]


def номер(п):
    return "В-" + п["id"].split("-", 1)[1]


def сума(п):
    н = налаштування.всі()
    # Чек — із Syrve, а не зі слів тайника; анкета — лише поки звірки немає.
    з = ((п.get("syrve") or {}).get("замовлення") or {})
    if з.get("сума") is not None:
        чек, джерело = float(з["сума"]), "Syrve"
    else:
        чек, джерело = float(перевірки.відповідь(п, "сума_замовлення") or 0), "анкета"
    компенсація = min(чек, н["ліміт_замовлення"], н["макс_компенсація"])
    return {"чек": чек, "компенсація": round(компенсація), "ставка": н["ставка_за_анкету"],
            "разом": round(компенсація + н["ставка_за_анкету"]), "джерело_чека": джерело}


def створити(п, хто="агент"):
    в = {"номер": номер(п), "статус": "у черзі на виплату", **сума(п),
         "створено": datetime.now().isoformat(timespec="seconds"), "історія": []}
    п["виплата"] = в
    перевірки.зберегти(п)
    журнал.запис(хто, "виплата:заявка", в["номер"], f"{в['разом']} грн = чек {в['компенсація']} + ставка {в['ставка']}")
    return в


def статус(п, новий, хто, чому=""):
    в = п["виплата"]
    в["історія"].append({"коли": datetime.now().isoformat(timespec="seconds"), "з": в["статус"], "у": новий, "хто": хто, "чому": чому})
    в["статус"] = новий
    if новий == "виплачена":
        в["виплачено"] = datetime.now().isoformat(timespec="seconds")
    перевірки.зберегти(п)
    журнал.запис(хто, f"виплата:{новий}", в["номер"], чому)
    return в


def у_черзі():
    return [п for п in перевірки.усі() if (п.get("виплата") or {}).get("статус") == "у черзі на виплату"]


def чекають_підтвердження():
    return [п for п in перевірки.усі() if (п.get("виплата") or {}).get("статус") == "виплачена"]


def прострочені():
    """Заявки, що висять довше SLA — нагадати адміну."""
    sla = налаштування.дай("sla_виплати_днів")
    зараз = datetime.now()
    return [п for п in у_черзі() if (зараз - datetime.fromisoformat(п["виплата"]["створено"])).days >= sla]


def непідтверджені():
    днів = налаштування.дай("нагадати_отримання_днів")
    зараз = datetime.now()
    return [п for п in чекають_підтвердження() if (зараз - datetime.fromisoformat(п["виплата"]["виплачено"])).days >= днів]


def картка(п):
    в = п["виплата"]
    о = п.get("оцінка") or {}
    return "\n".join([
        f"💸 <b>Заявка {в['номер']}</b> · перевірка {п['id']}",
        f"Тайник: <b>{тайники.номер(п['тайник'])}</b>",
        f"Філія: {п['філія']} · {п['канал']} · {п['вікно']['дата']}",
        f"Чек ({в.get('джерело_чека', 'анкета')}): {в['чек']:.0f} грн → компенсація <b>{в['компенсація']}</b> + ставка {в['ставка']} = <b>{в['разом']} грн</b>",
        f"Оцінка перевірки: {о.get('загальна', '—')}% ({о.get('зона', '—')})",
        f"Статус: {в['статус']}",
    ])


def реєстр(від=None, до=None):
    res = []
    for п in перевірки.усі():
        в = п.get("виплата")
        if not в:
            continue
        if від and в["створено"] < від:
            continue
        if до and в["створено"] >= до:
            continue
        res.append(п)
    return sorted(res, key=lambda п: п["виплата"]["створено"])


def бюджет_місяця():
    місяць = datetime.now().strftime("%Y-%m")
    заявки = [п["виплата"] for п in реєстр(від=місяць) if п["виплата"]["статус"] not in ("відхилена",)]
    витрачено = sum(в["разом"] for в in заявки)
    ліміт = налаштування.дай("бюджет_на_місяць")
    return {"місяць": місяць, "заявок": len(заявки), "витрачено": витрачено,
            "середня": round(витрачено / len(заявки)) if заявки else 0, "ліміт": ліміт,
            "залишок": (ліміт - витрачено) if ліміт else None}
