# ---------------------------------------------------------------- матриця
def _час_доби(вікно_від):
    пік = налаштування.дай("пік")
    return "пік" if пік[0] <= вікно_від < пік[1] else "непік"


def _день(дата):
    return "вихідні" if datetime.fromisoformat(дата).weekday() >= 5 else "будні"


def факт_покриття(днів=90):
    """Скільки перевірок за квартал припало на кожне значення зрізу."""
    від = (datetime.now() - timedelta(days=днів)).date().isoformat()
    лічильники = {"філія": {}, "канал": {}, "час": {}, "день": {}, "категорія": {}}
    # «завдання видано» теж рахується: воно вже займає зріз, навіть якщо
    # акцепту ще немає — інакше два слоти однієї хвилі отримають одне й те саме.
    for п in перевірки.за_період(від, статуси={"завдання видано", "акцептовано", "в виконанні", "анкета здана",
                                               "на автоперевірці", "на ревю", "прийнята", "на доробці", "закрита"}):
        лічильники["філія"][п["філія"]] = лічильники["філія"].get(п["філія"], 0) + 1
        лічильники["канал"][п["канал"]] = лічильники["канал"].get(п["канал"], 0) + 1
        ч = _час_доби(п["вікно"]["від"])
        лічильники["час"][ч] = лічильники["час"].get(ч, 0) + 1
        д = _день(п["вікно"]["дата"])
        лічильники["день"][д] = лічильники["день"].get(д, 0) + 1
        for поз in (п.get("завдання") or {}).get("позиції", []):
            к = поз.get("категорія")
            if к:
                лічильники["категорія"][к] = лічильники["категорія"].get(к, 0) + 1
    return лічильники


def значення_зрізів():
    н = налаштування.всі()
    return {"філія": н["філії"], "канал": н["канали_активні"], "час": ["пік", "непік"],
            "день": ["будні", "вихідні"], "категорія": еталони.категорії_покриті() or н["категорії"]}


def відставання(факт=None):
    """Для кожного зрізу — значення, відсортовані від найбільш відсталого.

    При рівному відставанні — порядок із налаштувань: там категорії
    стоять за пріоритетом (суші та роли, піца — ядро меню), канали — за
    важливістю. Так перша хвиля не починається з лимонаду.
    """
    факт = факт or факт_покриття()
    пріоритет = {"категорія": налаштування.дай("категорії"), "канал": налаштування.дай("канали")}
    res = {}
    for зріз, значення in значення_зрізів().items():
        всього = sum(факт[зріз].get(з, 0) for з in значення) or 0
        ціль = 1 / len(значення) if значення else 0
        пор = пріоритет.get(зріз) or list(значення)
        res[зріз] = sorted(значення, key=lambda з: (-(ціль - (факт[зріз].get(з, 0) / всього if всього else 0)),
                                                    пор.index(з) if з in пор else 99))
    return res


def матриця_текстом():
    факт = факт_покриття()
    рядки = []
    for зріз, значення in значення_зрізів().items():
        всього = sum(факт[зріз].get(з, 0) for з in значення)
        частки = ", ".join(f"{з} {факт[зріз].get(з, 0)}" + (f" ({round(100 * факт[зріз].get(з, 0) / всього)}%)" if всього else "")
                           for з in значення)
        рядки.append(f"{зріз}: {частки}")
    return "\n".join(рядки)


