def текст(п):
    """Завдання людською мовою — те, що бачить тайник перед акцептом."""
    з = п["завдання"]
    в = з["вікно"]
    рядки = [f"🕵️ <b>Завдання {п['id']}</b>", "",
             f"📍 Філія: <b>{з['філія']}</b>",
             f"🛒 Канал: <b>{з['канал']}</b>",
             f"📅 Коли: <b>{в['дата']}</b>, оформити між <b>{в['від']}</b> і <b>{в['до']}</b>",
             "", "<b>Замовити обов'язково:</b>"]
    for поз in з["позиції"]:
        рядки.append(f"  • {поз['назва']}" + (f" — {поз['ціна']} грн" if поз.get("ціна") else ""))
    if з["на_вибір"]:
        рядки.append("<b>За бажанням одне з:</b> " + ", ".join(п_["назва"] for п_ in з["на_вибір"]))
    рядки += ["", f"💰 Ліміт замовлення: <b>{з['бюджет']} грн</b>. {з['при_перевищенні']}",
              f"⛔ Стоп-лист: {з['при_стоплисті']}",
              f"💳 Оплата: {з['оплата']}", "",
              "<b>На що дивитись:</b>"]
    рядки += [f"  • {м}" for м in з["памятка"]]
    рядки += [f"  ❗ {у}" for у in (з.get("увага") or [])]
    if з.get("провокація"):
        пр = з["провокація"]
        рядки += ["", f"<b>Сценарій ({пр['адресат']}):</b> {пр['дія']}",
                  f"  Перевіряємо: {пр['що_перевіряємо']}",
                  f"  Норма: {пр['еталон_реакції']}",
                  "  Без конфліктів і без грубості з твого боку — ти звичайний клієнт."]
    рядки += ["", "<b>Фото обов'язково:</b>"] + [f"  • {д}" for д in з["докази"]]
    рядки += ["", "<b>Конспірація:</b>"] + [f"  • {к}" for к in з["конспірація"]]
    рядки += ["", f"⏳ Анкету здати протягом <b>{з['дедлайн_анкети_годин']} год</b> після отримання.",
              "Компенсація: сума чека (у ліміті) + ставка за анкету після приймання."]
    return "\n".join(рядки)
