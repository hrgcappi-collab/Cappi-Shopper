def план_хвилі(скільки=None, тиждень=None):
    """Параметри слотів на наступну хвилю: найвідсталіші зрізи, без
    повторів між слотами однієї хвилі."""
    import хвилі
    скільки = скільки or налаштування.дай("слотів_у_хвилі")
    пн = тиждень or хвилі.наступний_тиждень()
    відст = відставання()
    повтори = loopa.повтори_до_планування()
    слоти = []
    for i in range(скільки):
        філія = відст["філія"][i % len(відст["філія"])]
        канал = відст["канал"][i % len(відст["канал"])]
        повтор = None
        if повтори:
            # Закритий тікет: той самий зріз перевіряємо повторно — перший слот його.
            т = повтори.pop(0)
            філія, повтор = т["філія"], т["id"]
            if т["канал"] in налаштування.дай("канали_активні"):
                канал = т["канал"]
        час = відст["час"][i % 2]
        день = відст["день"][i % 2]
        дата = пн + timedelta(days=5 if день == "вихідні" else 3)      # субота або четвер
        від, до = (налаштування.дай("пік") if час == "пік" else ["12:00", "17:00"])
        слоти.append({"дата": дата.isoformat(), "від": від, "до": до, "філія": філія, "канал": канал,
                      "зріз": {"час": час, "день": день}, "повтор_тікета": повтор})
    return слоти


# ---------------------------------------------------------------- завдання
def _скільки_перевірялась(id_, днів=90):
    від = (datetime.now() - timedelta(days=днів)).date().isoformat()
    return sum(1 for п in перевірки.за_період(від)
               for поз in (п.get("завдання") or {}).get("позиції", []) if поз["id"] == id_)


def _у_стопі():
    """id товарів у стоп-листі хоч на одній точці; Syrve мовчить — порожньо."""
    if not syrve.налаштовано():
        return set()
    try:
        return set(syrve.стоплист())
    except syrve.Недоступний:
        return set()


def підібрати_позиції(ліміт, категорії_за_відставанням):
    """2 обов'язкові з різних найвідсталіших категорій + 1 на вибір, у ліміт.
    Позиція в стоп-листі на момент генерації не пропонується."""
    сьогодні = datetime.now().date().isoformat()
    стоп = _у_стопі()
    кандидати = [к for к in еталони.опубліковані()
                 if (not к.get("запущено") or (datetime.fromisoformat(к["запущено"]).date() + timedelta(days=7)).isoformat() <= сьогодні)
                 and еталони.syrve_id(к) not in стоп]
    обовязкові, сума = [], 0
    for кат in категорії_за_відставанням:
        if len(обовязкові) >= 2:
            break
        # Найдавніше не перевірялась; при рівності — ходовіша за ABC (ТЗ 7: пріоритет ходовим).
        import імпорт
        варіанти = sorted((к for к in кандидати if к["категорія"] == кат and к not in обовязкові),
                          key=lambda к: (_скільки_перевірялась(к["id"]), імпорт.abc_ранг(к), к.get("ціна", 0)))
        for к in варіанти:
            if сума + (к.get("ціна") or 0) <= ліміт:
                обовязкові.append(к)
                сума += к.get("ціна") or 0
                break
    на_вибір = [к for к in кандидати if к not in обовязкові and сума + (к.get("ціна") or 0) <= ліміт][:3]
    return обовязкові, на_вибір, сума


def _позиція(к):
    # id — Syrve, якщо картка прив'язана: тоді звірка складу йде по id, а не по назві.
    return {"id": еталони.syrve_id(к) or к["id"], "еталон_id": к["id"], "назва": к["назва"], "категорія": к["категорія"], "ціна": к.get("ціна"),
            "еталон": {"версія": к.get("версія"), "ознаки": к.get("ознаки", []), "шматків": к.get("шматків"),
                       "комплектність": к.get("комплектність", []), "упаковка": к.get("упаковка"),
                       "фірмове": к.get("фірмове", "")}}


