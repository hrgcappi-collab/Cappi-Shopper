def kpi():
    м = datetime.now().strftime("%Y-%m")
    пп = [п for п in перевірки.усі() if (п["анкета"].get("здано") or "")[:7] == м and п.get("оцінка")]
    б = виплати.бюджет_місяця()
    сер = round(sum(п["оцінка"]["загальна"] for п in пп if п["оцінка"]["загальна"] is not None) / max(1, len([п for п in пп if п["оцінка"]["загальна"] is not None]))) if пп else None
    return {"місяць": м, "перевірок": len(пп), "на_ревю": len(перевірки.усі("на ревю")), "червона_зона": sum(1 for п in пп if оцінка.червона(п["оцінка"])),
            "виплати_чекають": len(виплати.у_черзі()) + len(виплати.чекають_підтвердження()), "середня_оцінка": сер,
            "витрачено": б["витрачено"], "ліміт": б["ліміт"], "активних_тайників": len(тайники.активні())}


def аналітика():
    """Динаміка по групах по тижнях, обіцяно/факт, тайники проти клієнтів."""
    тижні = {}
    for п in перевірки.усі():
        о = п.get("оцінка")
        if not о or п["статус"] not in ("прийнята", "закрита"):
            continue
        д = datetime.fromisoformat(п["анкета"]["здано"])
        ключ = f"{д.isocalendar()[0]}-Т{д.isocalendar()[1]:02d}"
        т = тижні.setdefault(ключ, {})
        for г, гр in о["групи"].items():
            if гр.get("відсоток") is not None:
                т.setdefault(г, []).append(гр["відсоток"])
    динаміка = {к: {г: round(sum(v) / len(v)) for г, v in т.items()} for к, т in sorted(тижні.items())}
    зап = [(п["оцінка"]["запізнення_хв"], п["канал"]) for п in перевірки.усі() if (п.get("оцінка") or {}).get("запізнення_хв") is not None]
    відх = sorted(з for з, _ in зап)
    медіана = відх[len(відх) // 2] if відх else None
    негатив = loopa.негатив(30)
    по_філіях = {}
    for п in перевірки.усі():
        о = п.get("оцінка")
        if о and о.get("загальна") is not None and п["статус"] in ("прийнята", "закрита"):
            по_філіях.setdefault(п["філія"], []).append(о["загальна"])
    return {"динаміка_тижні": динаміка,
            "обіцяно_факт": {"медіана_відхилення_хв": медіана, "у_межах": sum(1 for з, _ in зап if з <= 0), "усього": len(зап),
                             "найбільше": max(зап, key=lambda x: x[0]) if зап else None},
            "тайники_проти_клієнтів": {ф: {"тайники": round(sum(v) / len(v)), "скарг_клієнтів_30дн": (негатив or {}).get("філії", {}).get(ф)} for ф, v in по_філіях.items()},
            "матриця": {"факт": завдання.факт_покриття(), "відставання": завдання.відставання()},
            "негатив_loopa": негатив}


