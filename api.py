def _тайник(т, pii):
    res = {"id": т["номер"], "статус": т["статус"], "район": (т.get("анкета") or {}).get("район") if pii else None,
           "канали": (т.get("анкета") or {}).get("канали") or [], "перевірок": т["перевірок"],
           "рейтинг": т["рейтинг"], "рейтинг100": round(т["рейтинг"] * 20), "остання": т.get("остання_перевірка"),
           "кулдаун_до": т.get("кулдаун_до") if тайники.у_кулдауні(т["uid"]) else None,
           "згоди": bool(т.get("згоди")), "інструктаж": bool(т.get("інструктаж")), "зриви": т.get("зриви", 0),
           "зареєстровано": т.get("зареєстровано"), "блеклист": т.get("блеклист")}
    if pii:
        res.update({"uid": т["uid"], "імя": т.get("імя"), "телефон": т.get("телефон"), "username": т.get("username"),
                    "реквізити": т.get("реквізити")})
    return res


def _перевірка_коротко(п):
    о = п.get("оцінка") or {}
    в = п.get("виплата") or {}
    з = (п.get("syrve") or {}).get("замовлення") or {}
    return {"id": п["id"], "статус": п["статус"], "філія": п["філія"], "канал": п["канал"], "вікно": п["вікно"],
            "тайник": тайники.номер(п["тайник"]) if п.get("тайник") else None,
            "позиції": [x["назва"] for x in (п.get("завдання") or {}).get("позиції", [])],
            "провокація": ((п.get("завдання") or {}).get("провокація") or {}).get("код"),
            "оцінка": о.get("загальна"), "зона": о.get("зона"), "критичні": len(о.get("критичні", [])),
            "замовлення": з.get("номер"), "сума": з.get("сума") or п["анкета"]["відповіді"].get("сума_замовлення"),
            "виплата": {"номер": в.get("номер"), "статус": в.get("статус"), "разом": в.get("разом")} if в else None,
            "здано": п["анкета"].get("здано"), "створено": п["створено"], "повтор_тікета": п.get("повтор_тікета"),
            "рекомендація": (п.get("приймання") or {}).get("рекомендація")}


def _перевірка_повно(п, pii):
    в = п["анкета"]["відповіді"]
    блоки = []
    for к in анкета.усі_кроки(п):
        if not блоки or блоки[-1]["код"] != к["блок"]:
            блоки.append({"код": к["блок"], "назва": к["блок_назва"], "група": к.get("група"), "питання": []})
        блоки[-1]["питання"].append({"код": к["код"], "питання": к["питання"], "тип": к["тип"], "група": к.get("група"),
                                     "відповідь": в.get(к["код"]), "показ": звіти.показати(к, в.get(к["код"])),
                                     "позиція": к.get("позиція"), "вага": к.get("вага"), "критично": bool(к.get("критично") or к.get("критичні"))})
    р = п.get("приймання") or {}
    return {**_перевірка_коротко(п),
            "завдання": п.get("завдання"),
            "анкета": {"версія": п["анкета"].get("версія"), "етап_до": п["анкета"].get("етап_до"), "здано": п["анкета"].get("здано"), "блоки": блоки},
            "приймання": р, "syrve": п.get("syrve"), "оцінка_повна": п.get("оцінка") or (оцінка.порахувати(п) if в else None),
            "медіа": [{"код": к["код"], "підпис": к["питання"], "file_id": в[к["код"]], "url": f"/api/media/{в[к['код']]}"}
                      for к in анкета.усі_кроки(п) if к["тип"] == "фото" and в.get(к["код"]) and в[к["код"]] != "знеособлено"],
            "історія": п.get("історія", []), "журнал": журнал.по_обєкту(п["id"]),
            "виплата_повна": п.get("виплата"), "форс_мажор": п.get("форс_мажор"), "нагадано": п.get("нагадано"),
            "тайник_картка": _тайник(тайники.картка(п["тайник"]), pii) if п.get("тайник") and тайники.картка(п["тайник"]) else None}


