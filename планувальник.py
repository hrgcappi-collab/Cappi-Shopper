#!/usr/bin/env python3
"""Те, що агент робить сам по годиннику — ТЗ розділи 4, 8, 16, 17.

Раз на хвилину:
- тайм-аут акцепту: 12 годин минуло — слот іде наступному в черзі;
- нагадування тайнику: за день до вікна, у день вікна, через годину
  після очікуваного отримання — заповнити анкету, перед дедлайном;
- доробка прострочена — сигнал маркетологу;
- виплата висить понад SLA — нагадати адміну; отримання не
  підтверджено два дні — нагадати тайнику;
- понеділок 10:00: тижнева зводка керівництву, дайджест маркетологу,
  нова хвиля, якщо відкритої немає.

Усе, що відправлено, позначається в об'єкті («нагадано»), щоб після
перезапуску не надіслати вдруге.
"""
import threading
import time
import traceback
from datetime import datetime, timedelta

import виплати
import журнал
import налаштування
import перевірки
import тайники
import хвилі

_дії = {}      # заповнює bot.py: назва → функція; планувальник не знає Telegram


def підключити(**дії):
    _дії.update(дії)


def _раз(п, ключ):
    """True один раз для кожного ключа нагадування у перевірці."""
    н = п.setdefault("нагадано", {})
    if н.get(ключ):
        return False
    н[ключ] = datetime.now().isoformat(timespec="seconds")
    перевірки.зберегти(п)
    return True


def тік(зараз=None):
    зараз = зараз or datetime.now()
    сьогодні = зараз.date().isoformat()
    завтра = (зараз.date() + timedelta(days=1)).isoformat()

    for п in перевірки.усі():
        с = п["статус"]
        # --- тайм-аут акцепту
        if с == "завдання видано" and п.get("акцепт_до") and зараз.isoformat() > п["акцепт_до"]:
            _дії["зрив_акцепту"](п)
            continue
        # --- нагадування перед виконанням
        if с == "акцептовано":
            if п["вікно"]["дата"] == завтра and зараз.hour >= 10 and _раз(п, "за_день"):
                _дії["нагадати"](п, f"Нагадую: завтра {п['вікно']['дата']} з {п['вікно']['від']} до {п['вікно']['до']} — твоє замовлення у {п['філія']}. Завдання — кнопка «Моє завдання».")
            if п["вікно"]["дата"] == сьогодні and зараз.hour >= 10 and _раз(п, "у_день"):
                _дії["нагадати"](п, f"Сьогодні з {п['вікно']['від']} до {п['вікно']['до']} — оформлюй замовлення. Одразу після оформлення відкрий «Анкета» і заповни перший блок.")
            if п["вікно"]["дата"] < сьогодні and _раз(п, "пропустив_вікно"):
                _дії["сигнал"](п, f"⚠️ {п['id']}: вікно {п['вікно']['дата']} минуло, анкети немає. Тайник {тайники.номер(п['тайник'])}.")
        # --- після оформлення: чекаємо отримання і анкету
        if с == "в виконанні":
            в = п["анкета"]["відповіді"]
            try:
                очікуване = datetime.fromisoformat(в["час_оформлення"]) + timedelta(minutes=int(в.get("обіцяний_час") or 60))
            except (KeyError, ValueError, TypeError):
                очікуване = None
            if очікуване and зараз > очікуване + timedelta(hours=1) and _раз(п, "заповнити"):
                _дії["нагадати"](п, "Замовлення вже мало приїхати. Коли отримаєш — «Анкета», другий блок. Здати треба протягом доби після отримання.")
            if очікуване and зараз > очікуване + timedelta(hours=п["завдання"]["дедлайн_анкети_годин"] - 3) and _раз(п, "дедлайн"):
                _дії["нагадати"](п, "До дедлайну анкети лишилось близько 3 годин. Після дедлайну виплата є, але рейтинг нижче.")
        # --- доробка прострочена
        if с == "на доробці" and п.get("доробка_до") and зараз.isoformat() > п["доробка_до"] and _раз(п, "доробка_прострочена"):
            _дії["сигнал"](п, f"⏰ {п['id']}: доробка прострочена. За правилами — відмова у виплаті; рішення за тобою.")
    # --- відкладена звірка з Syrve: раз на годину, поки не вдасться
    if зараз.minute < 1:
        for п in перевірки.усі():
            if п.get("syrve_відкладено") and п["статус"] in ("на ревю", "прийнята", "на доробці"):
                _дії["повторити_syrve"](п)
    # --- виплати
    for п in виплати.прострочені():
        if _раз(п, "sla_виплати"):
            _дії["нагадати_адміну"](п)
    for п in виплати.непідтверджені():
        if _раз(п, "підтвердити_отримання"):
            _дії["спитати_отримання"](п)
    # --- понеділок 10:00
    if зараз.weekday() == 0 and зараз.hour == 10:
        мітка = сховище_мітка("тиждень")
        if мітка != сьогодні:
            сховище_мітка("тиждень", сьогодні)
            _дії["тижневі_звіти"]()
            if налаштування.дай("автохвилі") and not хвилі.відкрита():
                _дії["нова_хвиля"]()


def сховище_мітка(ключ, значення=None):
    import сховище
    м = сховище.json_читати("мітки.json", {})
    if значення is None:
        return м.get(ключ)
    м[ключ] = значення
    сховище.json_писати("мітки.json", м)
    return значення


def запустити():
    def цикл():
        while True:
            try:
                тік()
            except Exception:
                traceback.print_exc()
            time.sleep(60)
    threading.Thread(target=цикл, name="планувальник", daemon=True).start()
