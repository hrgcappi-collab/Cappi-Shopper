def готовий_до_завдань(uid):
    т = картка(uid)
    return bool(т and т["статус"] == "активний" and т.get("згоди") and т.get("інструктаж"))


def чого_бракує(uid):
    т = картка(uid)
    if not т:
        return "реєстрація"
    if т["статус"] == "кандидат":
        return "активація"
    if т["статус"] != "активний":
        return т["статус"]
    if not т.get("згоди"):
        return "згоди"
    if not т.get("інструктаж"):
        return "інструктаж"
    return None


def у_кулдауні(uid, на_дату=None):
    """True, якщо на дату слота людина ще «відпочиває» після минулої перевірки."""
    т = картка(uid)
    if not т or not т.get("кулдаун_до"):
        return False
    дата = (на_дату or datetime.now().date().isoformat())[:10]
    return дата < т["кулдаун_до"][:10]


def відмітити_виконання(uid, дата_замовлення, хто="агент"):
    т = картка(uid)
    т["перевірок"] += 1
    т["остання_перевірка"] = дата_замовлення[:10]
    днів = налаштування.кулдаун_днів(len(активні()))
    т["кулдаун_до"] = (datetime.fromisoformat(дата_замовлення[:10]) + timedelta(days=днів)).date().isoformat()
    _зберегти()


def подвоїти_кулдаун(uid, хто, чому):
    т = картка(uid)
    днів = налаштування.кулдаун_днів(len(активні()))
    база = datetime.fromisoformat(т["кулдаун_до"]) if т.get("кулдаун_до") else datetime.now()
    т["кулдаун_до"] = (max(база, datetime.now()) + timedelta(days=днів)).date().isoformat()
    т["зриви"] = т.get("зриви", 0) + 1
    _зберегти()
    журнал.запис(хто, "кулдаун×2", т["номер"], чому)
    return т["зриви"]


def оновити_рейтинг(uid, бал_анкети, хто="агент", чому=""):
    """Рейтинг — ковзне середнє якості анкет, 1–5."""
    т = картка(uid)
    т["рейтинг"] = round(т["рейтинг"] * 0.7 + бал_анкети * 0.3, 2)
    _зберегти()
    журнал.запис(хто, "рейтинг", т["номер"], f"{бал_анкети} → {т['рейтинг']} {чому}")


