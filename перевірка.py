#!/usr/bin/env python3
"""Хід однієї перевірки: від вибору філії до готового чек-листа.

Сценарій — у сценарій.json, тут лише механіка: який крок зараз, що
вважати відповіддю, куди її класти. Бот не знає, які питання в чек-листі,
а сценарій не знає про Telegram — тому ТЗ, коли з'явиться, ляже у json,
а код лишиться той самий.

Незавершені перевірки лежать у ~/.shopper/сесії.json і переживають
перезапуск бота: тайний гість може півгодини чекати кур'єра, і втратити
за цей час уже внесене — означає, що він перевірку кине.

Завершені — рядками у перевірки.jsonl. Формат запису нижче у `завершити`;
саме його потім читатиме Core для показника «тайний гість».
"""
import json
import os
import time
from datetime import datetime

import сховище

ТИПИ = {"оцінка", "так_ні", "вибір", "текст", "число", "фото", "час"}
ФАЙЛ_СЕСІЙ = "сесії.json"
ФАЙЛ_ЖУРНАЛУ = "перевірки.jsonl"

_сценарій = None
_сесії = None


def сценарій():
    global _сценарій
    if _сценарій is None:
        тут = os.path.dirname(os.path.abspath(__file__))
        with open(os.path.join(тут, "сценарій.json"), encoding="utf-8") as f:
            _сценарій = json.load(f)
    return _сценарій


def перевірити_сценарій(с=None):
    """Повертає список помилок формату. Порожній — усе гаразд.

    Викликається із selftest, щоб зламаний json ловився до деплою, а не
    на п'ятому кроці у живого перевіряючого.
    """
    с = с or сценарій()
    помилки = []
    if not с.get("філії"):
        помилки.append("немає філій")
    if not с.get("канали"):
        помилки.append("немає каналів")
    коди = set()
    for р in с.get("розділи", []):
        if not р.get("код") or not р.get("назва"):
            помилки.append(f"розділ без коду або назви: {р}")
        for к in р.get("кроки", []):
            код = к.get("код")
            if not код:
                помилки.append(f"крок без коду у розділі {р.get('код')}")
                continue
            if код in коди:
                помилки.append(f"код кроку повторюється: {код}")
            коди.add(код)
            if к.get("тип") not in ТИПИ:
                помилки.append(f"{код}: невідомий тип {к.get('тип')!r}")
            if not к.get("питання"):
                помилки.append(f"{код}: немає питання")
            if к.get("тип") == "вибір":
                if not к.get("варіанти"):
                    помилки.append(f"{код}: вибір без варіантів")
                зайві = set(к.get("бали", {})) - set(к.get("варіанти", []))
                if зайві:
                    помилки.append(f"{код}: бали для неіснуючих варіантів {зайві}")
            if к.get("тип") == "так_ні" and "вага" in к and "очікується" not in к:
                помилки.append(f"{код}: так_ні з вагою, але без «очікується»")
            for кан in к.get("канали", []):
                if кан not in с["канали"]:
                    помилки.append(f"{код}: невідомий канал {кан}")
    if not коди:
        помилки.append("жодного кроку")
    return помилки


# ---------------------------------------------------------------- сесії
def _завантажити():
    global _сесії
    if _сесії is None:
        _сесії = {str(k): v for k, v in сховище.json_читати(ФАЙЛ_СЕСІЙ, {}).items()}
    return _сесії


def _зберегти():
    сховище.json_писати(ФАЙЛ_СЕСІЙ, _завантажити())


def поточна(chat):
    return _завантажити().get(str(chat))


def почати(chat, хто):
    """Нова перевірка. Філія і канал ще не обрані — це перші два екрани."""
    с = {
        "chat": chat,
        "хто": хто,
        "почато": datetime.now().isoformat(timespec="seconds"),
        "філія": None,
        "канал": None,
        "крок": 0,
        "відповіді": {},
        "версія_сценарію": сценарій().get("версія"),
    }
    _завантажити()[str(chat)] = с
    _зберегти()
    return с


def скасувати(chat):
    _завантажити().pop(str(chat), None)
    _зберегти()


def обрати(chat, поле, значення):
    с = поточна(chat)
    с[поле] = значення
    _зберегти()


def кроки(с):
    """Плоский список кроків для цієї перевірки з урахуванням каналу.

    Крок із полем «канали» показується лише на цих каналах: питання про
    ввічливість оператора немає сенсу ставити тому, хто замовляв на сайті.
    """
    res = []
    for р in сценарій()["розділи"]:
        for к in р["кроки"]:
            if к.get("канали") and с.get("канал") not in к["канали"]:
                continue
            res.append(dict(к, розділ=р["код"], розділ_назва=р["назва"]))
    return res


def крок(с):
    вс = кроки(с)
    i = с.get("крок", 0)
    return вс[i] if 0 <= i < len(вс) else None


def прогрес(с):
    return с.get("крок", 0) + 1, len(кроки(с))


def обовязковий(к):
    return к.get("обов", True)


def відповісти(chat, значення):
    """Кладе відповідь на поточний крок і рухає вперед.

    Повертає наступний крок або None, якщо чек-лист пройдено.
    """
    с = поточна(chat)
    к = крок(с)
    if к is None:
        return None
    с["відповіді"][к["код"]] = значення
    с["крок"] += 1
    _зберегти()
    return крок(с)


def пропустити(chat):
    с = поточна(chat)
    к = крок(с)
    if к is None or обовязковий(к):
        return крок(с)
    с["відповіді"].pop(к["код"], None)
    с["крок"] += 1
    _зберегти()
    return крок(с)


def назад(chat):
    с = поточна(chat)
    if с["крок"] > 0:
        с["крок"] -= 1
        _зберегти()
    return крок(с)


def перейти(chat, код):
    """Стрибок на конкретний крок — для кнопки «Виправити» у підсумку."""
    с = поточна(chat)
    for i, к in enumerate(кроки(с)):
        if к["код"] == код:
            с["крок"] = i
            _зберегти()
            return к
    return None


def до_кінця(chat):
    с = поточна(chat)
    с["крок"] = len(кроки(с))
    _зберегти()


def розібрати(к, текст):
    """Текстова відповідь → значення потрібного типу, або None, якщо не підходить."""
    т = к["тип"]
    текст = (текст or "").strip()
    if т == "текст":
        return текст or None
    if т == "число":
        try:
            return float(текст.replace(",", ".").replace(" ", ""))
        except ValueError:
            return None
    if т == "оцінка":
        return int(текст) if текст in "12345" and len(текст) == 1 else None
    if т == "так_ні":
        н = текст.lower()
        if н in ("так", "да", "yes", "+", "1"):
            return True
        if н in ("ні", "нет", "no", "-", "0"):
            return False
        return None
    if т == "вибір":
        return текст if текст in к.get("варіанти", []) else None
    if т == "час":
        # Людина може набрати «14:35» замість натискання кнопки — тоді
        # це сьогоднішня дата з цим часом.
        try:
            г, х = текст.split(":")
            return datetime.now().replace(hour=int(г), minute=int(х), second=0).isoformat(timespec="seconds")
        except (ValueError, AttributeError):
            return None
    return None


def зараз():
    return datetime.now().isoformat(timespec="seconds")


def завершити(chat):
    """Переносить сесію у журнал. Повертає готовий запис."""
    import звіт
    с = поточна(chat)
    запис = {
        "id": f"{datetime.now():%Y%m%d-%H%M%S}-{chat}",
        "почато": с["почато"],
        "завершено": зараз(),
        "хто": с["хто"],
        "філія": с["філія"],
        "канал": с["канал"],
        "версія_сценарію": с.get("версія_сценарію"),
        "відповіді": с["відповіді"],
        "оцінка": звіт.оцінити(с),
    }
    сховище.jsonl_дописати(ФАЙЛ_ЖУРНАЛУ, запис)
    скасувати(chat)
    return запис


def журнал(uid=None, скільки=10):
    всі = сховище.jsonl_читати(ФАЙЛ_ЖУРНАЛУ)
    if uid is not None:
        всі = [з for з in всі if з["хто"].get("id") == uid]
    return всі[-скільки:]
