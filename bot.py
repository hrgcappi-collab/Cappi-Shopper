_ПУЛ = ThreadPoolExecutor(max_workers=8, thread_name_prefix="чат")
_ЗАМКИ = {}
_ЗАМКИ_LOCK = threading.Lock()


def _замок(chat):
    with _ЗАМКИ_LOCK:
        return _ЗАМКИ.setdefault(chat, threading.Lock())


def обробити(u):
    try:
        if "callback_query" in u:
            q = u["callback_query"]
            with _замок(q["message"]["chat"]["id"]):
                кнопка(q)
        elif "message" in u:
            with _замок(u["message"]["chat"]["id"]):
                повідомлення(u["message"])
    except Exception:
        traceback.print_exc()
        try:
            chat = (u.get("message") or u.get("callback_query", {}).get("message", {}))["chat"]["id"]
            тихо(chat, "Щось зламалось. Спробуй ще раз або натисни /start.")
        except Exception:
            pass


