def прийняти(п, хто, примітка=""):
    п["оцінка"] = оцінка.порахувати(п)
    перевірки.статус(п, "прийнята", хто, примітка or "анкету прийнято")
    бал = приймання.бал_якості_анкети(п)
    тайники.оновити_рейтинг(п["тайник"], бал, чому=п["id"])
    тайники.відмітити_виконання(п["тайник"], п["анкета"]["відповіді"].get("час_оформлення") or п["вікно"]["дата"])
    в = виплати.створити(п, хто)
    # тайнику — зворотний зв'язок
    тихо(п["тайник"], f"Анкету {п['id']} прийнято ✅ Якість анкети: {бал}/5. "
                      f"Заявка на виплату {в['номер']} на {в['разом']} грн пішла адміністратору."
                      + ("" if бал >= 4.5 else "\nНаступного разу: більше подробиць у враженні, всі фото з першого разу."))
    # адміну — заявка
    inline = [[{"text": "💸 Виплачено", "callback_data": f"г:виплатити:{п['id']}"},
               {"text": "🚫 Відхилити", "callback_data": f"г:відхилити:{п['id']}"}]]
    т = тайники.картка(п["тайник"]) or {}
    # Реквізити — лише в адмін-чат (ТЗ: бачать адміністратори, у робочі чати не потрапляють).
    у_чат("адмін", виплати.картка(п) + (f"\nРеквізити: <code>{е(т['реквізити'])}</code>" if т.get("реквізити") else "\n⚠️ Реквізити не вказані — тайнику надіслано нагадування"), inline=inline)
    if not т.get("реквізити"):
        тихо(п["тайник"], "Щоб отримати виплату, вкажи реквізити: «Мої виплати» → «Вказати реквізити».")
    loopa.надіслати_перевірку(п)
    б = виплати.бюджет_місяця()
    if б["ліміт"] and б["витрачено"] >= 0.8 * б["ліміт"] and not planner_мітка_бюджету(б["місяць"]):
        маркетологам(f"💸 Бюджет {б['місяць']}: витрачено {б['витрачено']} з {б['ліміт']} грн ({round(100 * б['витрачено'] / б['ліміт'])}%).")
    # у робочі чати
    розіслати_звіти(п)
    # хвиля закрилась?
    х = хвилі.дай(п["хвиля"])
    if х and all(с.get("перевірка") and перевірки.дай(с["перевірка"])["статус"] in ("прийнята", "закрита", "відхилена", "зрив") for с in х["слоти"]):
        хвилі.закрити(х)


def planner_мітка_бюджету(місяць):
    return планувальник.сховище_мітка("бюджет_80") == місяць or планувальник.сховище_мітка("бюджет_80", місяць) and False


def розіслати_звіти(п):
    о = п["оцінка"]
    негайно = налаштування.дай("звіти_негайно") or оцінка.червона(о)
    if not негайно:
        return
    підсумок = мозок.підсумок_звіту(п)
    inline = [[{"text": "👌 Прийнято", "callback_data": f"о:прийнято:{п['id']}"},
               {"text": "✋ Не згодні", "callback_data": f"о:не_згодні:{п['id']}"}]]
    for назва in звіти.чати_для(п):
        текст = звіти.звіт_у_чат(п, назва, підсумок)
        if not текст:
            continue
        if оцінка.червона(о):
            текст = "🔴 <b>Червона зона</b>\n" + текст
        chat = налаштування.чат(назва)
        if not chat:
            continue
        тихо(chat, текст, inline=inline, keys=False)
        if звіти.АДРЕСАТИ[назва].get("фото"):
            for підпис, file_id in звіти.фото(п, лише_позиції=True)[:6]:
                фото(chat, file_id, е(підпис))
    if оцінка.червона(о):
        чому = "Червона зона: " + ("; ".join(к["що"] for к in о["критичні"]) or f"загальна {о['загальна']}%")
        т = loopa.тікет(п, чому)
        маркетологам(loopa.текст_тікета(т))
    пров = (п.get("завдання") or {}).get("провокація")
    if пров and пров.get("тестове_звернення") and п["анкета"]["відповіді"].get("пров_зробив"):
        # Скарга-провокація потрапила в підтримку справжнім зверненням —
        # позначаємо тестовим, щоб не псувала статистику скарг і компенсацій.
        п["тестове_звернення"] = True
        перевірки.зберегти(п)
        т = loopa.тікет(п, f"Тестове звернення за сценарієм «{пров['дія']}»: {п['анкета']['відповіді']['пров_зробив']}", тестове=True)
        маркетологам(loopa.текст_тікета(т))


