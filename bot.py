def повторити_syrve(п):
    """Відкладена звірка: Syrve не відповідав під час здачі анкети."""
    р = приймання.перевірити(п)
    if п.get("syrve_відкладено"):
        return
    п["приймання"] = р
    if п["статус"] == "прийнята":
        п["оцінка"] = оцінка.порахувати(п)
    перевірки.зберегти(п)
    журнал.запис("агент", "syrve:звірено пізніше", п["id"], р["чому"])
    маркетологам(f"Syrve відповів по {п['id']}:\n" + "\n".join(syrve.текст(п.get("syrve"))))


def зрив_після_акцепту(п):
    """Вікно минуло, анкети немає, форс-мажору не було: зрив із санкціями."""
    перевірки.статус(п, "зрив", "агент", "акцептував і не виконав без попередження")
    зривів = тайники.зрив_після_акцепту(п["тайник"])
    тихо(п["тайник"], f"Завдання {п['id']} не виконано без попередження. Рейтинг знижено, наступне завдання — не раніше ніж через "
                      f"{налаштування.кулдаун_днів(len(тайники.активні())) * 2} днів. Якщо був форс-мажор — напиши в підтримку.")
    х = хвилі.дай(п["хвиля"])
    if х:
        хвилі.звільнити_слот(х, п["слот"], чому="зрив після акцепту")
    текст = f"⛔ {п['id']}: {тайники.номер(п['тайник'])} зірвав завдання після акцепту (зривів: {зривів})."
    if зривів >= 2:
        текст += " Повторно — підстава для блеклисту."
        маркетологам(текст, inline=[[{"text": "🚫 У блеклист", "callback_data": f"т:блеклист:{п['тайник']}"}]])
    else:
        маркетологам(текст)


