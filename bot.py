def маркетологам(text, inline=None):
    for uid in set(access.з_правом("вирішувати")):
        тихо(uid, text, inline=inline)


def координаторам(text, inline=None):
    кому = set(access.з_правом("підтримка")) or set(access.з_правом("вирішувати"))
    for uid in кому:
        тихо(uid, text, inline=inline)


def у_чат(назва, text, inline=None):
    """У робочий чат за назвою; якщо не підключений — маркетологам."""
    chat = налаштування.чат(назва)
    if chat:
        тихо(chat, text, inline=inline, keys=False)
        return chat
    маркетологам(f"<i>[чат «{назва}» не підключений]</i>\n" + text, inline=inline)
    return None


