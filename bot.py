def прийняти_файл(chat, m):
    """CSV/txt від маркетолога: еталони, співробітники, новинки, зміни."""
    д = m["document"]
    вид = імпорт.розпізнати(д.get("file_name", ""), m.get("caption", ""))
    if not вид:
        return say(chat, "Не зрозумів, що це за файл. Назви його або підпиши одним зі слів: " + ", ".join(імпорт.ФОРМАТИ) +
                         ".\nФормати:\n" + "\n".join(f"  <b>{в}</b>: <code>{е(ф)}</code>" for в, ф in імпорт.ФОРМАТИ.items()))
    if (д.get("file_size") or 0) > 5_000_000:
        return say(chat, "Завеликий файл — до 5 МБ.")
    try:
        текст = завантажити(д["file_id"])
        n, помилки = імпорт.прийняти(вид, текст)
    except Exception as e:
        return say(chat, f"Не вийшло розібрати: {е(str(e)[:200])}")
    журнал.запис(chat, f"імпорт:{вид}", д.get("file_name", ""), f"{n} записів" + (f", зауважень {len(помилки)}" if помилки else ""))
    відп = f"Прийняв <b>{вид}</b>: {n} записів."
    if помилки:
        відп += "\nЗауваження:\n" + "\n".join(f"  • {е(п)}" for п in помилки[:15])
    if вид == "еталони":
        import еталони
        відп += f"\nОпублікованих з ознаками: {len(еталони.опубліковані())}. Прив'язати до Syrve — /еталони."
    say(chat, відп)


