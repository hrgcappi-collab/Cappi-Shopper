def режим_текст(chat, р, текст):
    """Вільний текст поза формою: підтримка, відповіді, причини, налаштування."""
    вид = р["режим"]
    if вид == "підтримка":
        return підтримка_повідомлення(chat, текст)
    if вид == "реквізити":
        т = тайники.картка(chat)
        т["реквізити"] = текст.strip()
        тайники._зберегти()
        журнал.запис(chat, "реквізити", т["номер"], "оновлено (значення не журналюється)")
        збіги = тайники.збіги_між_тайниками(chat)
        if збіги:
            маркетологам(f"⚠️ Антифрод: {т['номер']} — " + "; ".join(збіги))
        return say(chat, f"Записав: <code>{е(_маска(текст))}</code>. Змінити можна там само.")
    if вид == "форс":
        п = перевірки.дай(р["перевірка"])
        п["форс_мажор"] = {"коли": форма.зараз(), "що": текст}
        перевірки.зберегти(п)
        журнал.запис(chat, "форс-мажор", п["id"], текст)
        say(chat, "Передав координатору. Рейтинг не постраждає — розберемось і напишемо.")
        координаторам(f"⚠️ Форс-мажор {п['id']} від {тайники.номер(chat)}:\n{е(текст)}",
                      inline=[[{"text": "✍️ Відповісти", "callback_data": f"с:відповісти:{chat}"},
                               {"text": "🔁 Звільнити слот", "callback_data": f"х:звільнити:{п['id']}"}]])
        return
    if вид == "відповідь":
        тихо(int(р["кому"]), f"💬 Координатор: {е(текст)}")
        підтримка.відповіли(int(р["кому"]), chat)
        say(chat, "Надіслано.")
        return
    if вид == "причина":
        п = перевірки.дай(р["перевірка"])
        дія = р["дія"]
        if дія == "доробка":
            на_доробку(п, chat, текст)
        elif дія == "відхилити":
            відхилити(п, chat, текст)
        elif дія == "виплата_відхилити":
            виплати.статус(п, "відхилена", chat, текст)
