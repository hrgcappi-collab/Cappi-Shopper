def звязати_еталони(chat):
    """Картки еталонів → товари Syrve за назвою; далі склад звіряється по id."""
    import еталони
    if not syrve.налаштовано():
        return say(chat, "Syrve Cloud не налаштовано.")
    try:
        ном = syrve.номенклатура()
    except syrve.Недоступний as e:
        return say(chat, f"Syrve не відповів: {е(str(e))}")
    знайдено, ні = еталони.звязати(ном)
    рядки = [f"Товарів у Syrve: {len(ном)}. Прив'язано карток: {len(еталони.звязки())}."]
    рядки += [f"  ✅ {е(а)} → {е(б)}" for а, б in знайдено[:20]]
    рядки += [f"  ❌ {е(н)} — не знайшов у Syrve, підпиши syrve_id у картці" for н in ні[:20]]
    say(chat, "\n".join(рядки))


def діагностика_syrve(chat, арг):
    """/syrve — чи бачимо замовлення; /syrve +380… [дата] — замовлення з номера.
    Персональні дані замовника не показуються, лише факти замовлення."""
    if not syrve.налаштовано():
        return say(chat, "Syrve Cloud не налаштовано: перевір SYRVE_CLOUD_URL, SYRVE_CLOUD_API_KEY, SYRVE_ORG_ID.")
    try:
        if арг and арг[0].startswith("+"):
            дата = арг[1] if len(арг) > 1 else datetime.now().date().isoformat()
            зз = [syrve.розібрати(o) for o in syrve.замовлення_за_телефоном(арг[0], дата)]
            if not зз:
                return say(chat, f"За {дата} ±1 день замовлень з цього номера немає.")
            рядки = [f"Знайдено {len(зз)}:"]
            for з in зз[:5]:
                рядки.append(f"№{з['номер']} · {з['філія'] or '?'} · {з['статус']} · {з['сума']} грн · створено {з['створено']} · "
                             f"доставлено {з['доставлено'] or '—'} · факт {з['факт_хв']} хв, обіцяно {з['обіцяно_хв']}")
                рядки.append("  " + ", ".join(f"{x['назва']}×{x['кількість']}" for x in з["позиції"][:8]))
            return say(chat, "\n".join(рядки))
        дата = арг[0] if арг else datetime.now().date().isoformat()
        зз = [syrve.розібрати(o) for o in syrve.замовлення_за_день(дата)]
        філії, статуси = {}, {}
        for з in зз:
            філії[з["філія"]] = філії.get(з["філія"], 0) + 1
            статуси[з["статус"]] = статуси.get(з["статус"], 0) + 1
        з_часом = [з for з in зз if з["факт_хв"] is not None]
        сер = round(sum(з["факт_хв"] for з in з_часом) / len(з_часом)) if з_часом else None
        return say(chat, f"Syrve Cloud відповідає. Замовлень за {дата}: {len(зз)}\n"
                         f"Філії: {філії}\nСтатуси: {статуси}\n"
                         f"Із часом вручення: {len(з_часом)}, середній факт {сер} хв.\n"
                         f"Перевірити номер: <code>/syrve +380671234567 {дата}</code>")
    except syrve.Недоступний as e:
        return say(chat, f"Syrve не відповів: {е(str(e))}")


def кнопка(q):
    chat = q["message"]["chat"]["id"]
    хто = q.get("from", {}).get("id", chat)
    дані = q.get("data", "")
    вид, _, решта = дані.partition(":")

    # ---- форми (будь-хто, у кого відкрита форма)
    if вид in ("в", "м", "п", "з"):
        с = форма.поточна(chat)
        if not с:
            return say(chat, "Ця форма вже закрита.")
        if вид == "в":
            к = форма.крок(с)
            if к is None:
                return екран_підсумку_форми(chat)
            if решта == "нд":
                значення = форма.НД
            elif к["тип"] == "час" and решта == "зараз":
                значення = форма.зараз()
            elif к["тип"] in ("так_ні", "згода"):
                значення = решта == "так"
            else:
                значення = форма.розібрати(к, решта)
            if значення is None:
                return say(chat, _підказка(к))
            return _відповісти(chat, значення)
        if вид == "м":
            к = форма.крок(с)
            if решта == "готово":
                if not с["відповіді"].get(к["код"]) and форма.обовязковий(к):
                    return say(chat, "Відміть хоча б один варіант.")
                return _відповісти(chat, с["відповіді"].get(к["код"]) or [])
            форма.перемкнути_вибір(chat, решта)
            return екран_кроку(chat)
        if вид == "п":
            форма.перейти(chat, решта)
            return екран_кроку(chat)
        if вид == "з":
            return завершити_форму(chat) if решта == "надіслати" else екран_виправити(chat)

    # ---- тайник
    if вид == "т" and решта == "тест":
        return почати_тест(chat)
    if вид == "т" and решта == "реквізити" and тайники.картка(chat):
        _режим_поставити(chat, {"режим": "реквізити"})
        return say(chat, "Напиши номер картки або IBAN і банк — одним рядком. Бачать лише адміністратори, у чати не потрапляє.")
    if вид == "х" and решта.startswith("відгук:"):
        return відгук(chat, решта.split(":", 1)[1])
    if вид == "а":
        так, п_id = решта.split(":", 1)
        п = перевірки.дай(п_id)
        if п and п["тайник"] == chat:
            return акцепт(chat, п, так == "так")
        return
    if вид == "ф":
        п = перевірки.дай(решта.split(":", 1)[1])
        if п and п["тайник"] == chat:
            return форс_мажор(chat, п)
        return
    if вид == "г" and решта.split(":")[0] in ("прийшли", "не_прийшли"):
        дія, п_id = решта.split(":", 1)
        п = перевірки.дай(п_id)
        if not п or п["тайник"] != chat:
            return
        if дія == "прийшли":
            виплати.статус(п, "підтверджена", chat, "тайник підтвердив отримання")
            перевірки.статус(п, "закрита", "агент", "виплату підтверджено — цикл закрито")
            return say(chat, "Дякую! Цикл закрито. До зустрічі в наступній хвилі.")
        виплати.статус(п, "спірна", chat, "тайник: гроші не прийшли")
        say(chat, "Записав. Координатор розбереться і напише.")
        return координаторам(f"❗ {п['виплата']['номер']}: {тайники.номер(chat)} каже, що гроші не прийшли.",
                             inline=[[{"text": "✍️ Відповісти", "callback_data": f"с:відповісти:{chat}"}]])

    # ---- зворотний зв'язок із робочих чатів
    if вид == "о":
        дія, п_id = решта.split(":", 1)
        ім = _хто(q.get("from", {}))["імя"]
        if дія == "прийнято":
            журнал.запис(хто, "звіт:прийнято", п_id, ім)
            return
        журнал.запис(хто, "звіт:не згодні", п_id, ім)
        return маркетологам(f"✋ Арбітраж: {е(ім)} не згоден з оцінкою {п_id}. Розібрати і зафіксувати рішення в журналі.")

