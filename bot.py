def повідомлення(m):
    chat = m["chat"]["id"]
    користувач = m.get("from", {})
    текст = (m.get("text") or "").strip()

    if chat < 0:                                      # групи: лише /чат і зворотний зв'язок
        if текст.startswith("/чат") and access.роль(користувач.get("id")):
            прив_язати_чат(chat)
        return

    # --- компанія
    if access.роль(chat):
        access.запамятати_імя(chat, _хто(користувач)["імя"])
        return повідомлення_компанії(chat, m, текст)

    # --- тайник або чужий
    т = тайники.картка(chat)
    if not т and not форма.поточна(chat):
        if текст.startswith("/start") or not текст:
            return старт_тайника(chat, користувач)
        return старт_тайника(chat, користувач)
    return повідомлення_тайника(chat, m, текст)


def _форма_або_режим(chat, m, текст):
    """Спільна частина: якщо йде форма або режим вводу — обробити. True = оброблено."""
    с = форма.поточна(chat)
    if с:
        if текст == ХІД["скасувати"]:
            форма.закрити(chat)
            if с["ключ"].startswith("анкета:"):
                п = перевірки.дай(с["контекст"]["перевірка"])
                п["анкета"]["відповіді"].update(с["відповіді"])       # чернетка лишається
                перевірки.зберегти(п)
                say(chat, "Анкету відклав, внесене збережено. Повернешся через «Анкета».")
            else:
                say(chat, "Скасовано.")
            return True
        if текст == ХІД["назад"]:
            форма.назад(chat)
            екран_кроку(chat)
            return True
        if текст == ХІД["пропустити"]:
            к = форма.крок(с)
            if к and форма.обовязковий(к):
                say(chat, "Цей крок обов'язковий.")
            else:
                форма.пропустити(chat)
                екран_кроку(chat)
            return True
        к = форма.крок(с)
        if к is None:
            екран_підсумку_форми(chat)
            return True
        if к["тип"] == "фото":
            file_id, uniq = None, None
            if m.get("photo"):
                file_id, uniq = m["photo"][-1]["file_id"], m["photo"][-1].get("file_unique_id")
            elif m.get("document") and str(m["document"].get("mime_type", "")).startswith("image/"):
                file_id, uniq = m["document"]["file_id"], m["document"].get("file_unique_id")
            if not file_id:
                say(chat, "Надішли фото" + ("" if форма.обовязковий(к) else " — або пропусти") + ".")
                return True
            if с["ключ"].startswith("анкета:") and uniq:
                п = перевірки.дай(с["контекст"]["перевірка"])
                п["анкета"].setdefault("фото_унікальні", {})[к["код"]] = uniq
                перевірки.зберегти(п)
            _відповісти(chat, file_id)
            return True
        if к["тип"] == "контакт" and m.get("contact"):
            _відповісти(chat, "+" + "".join(ч for ч in m["contact"]["phone_number"] if ч.isdigit()))
            return True
        if к["тип"] in ("вибір", "згода") and not (к["тип"] == "вибір" and текст in к.get("варіанти", [])):
            say(chat, "Обери варіант кнопкою.")
            return True
        значення = форма.розібрати(к, текст)
        if значення is None:
            say(chat, _підказка(к))
            return True
        _відповісти(chat, значення)
        return True

    р = _режим(chat)
    if р:
        if текст == ХІД["скасувати"]:
            _режим_поставити(chat, None)
            say(chat, "Скасовано.")
            return True
        if текст in (ХІД["назад"], ХІД["пропустити"]):
            say(chat, "Напиши текст або натисни «Скасувати».")
            return True
        _режим_поставити(chat, None)
        режим_текст(chat, р, текст)
        return True
    return False


