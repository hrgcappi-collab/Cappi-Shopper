#!/usr/bin/env python3
"""Усе, що маркетолог має право міняти без розробника: ставки, ліміти,
слоти, кулдаун, ваги груп, пороги зон, чати.

Значення за замовчуванням — тут; те, що змінили з бота, лежить у
~/.shopper/налаштування.json поверх них. Кожна зміна — запис у журнал
агента з тим, хто і що поміняв: ТЗ вимагає версіонування правил.
"""
