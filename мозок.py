#!/usr/bin/env python3
"""Штучний інтелект — там, де потрібен текст, а не правило.

Ключ — OPENAI_API_KEY у api.env (той самий, що у Core). Без ключа
модуль мовчить і повертає None: усе працює на шаблонах. Модель за
замовчуванням — та сама, що у Джамшута (OPENAI_MODEL).

Що робить: короткий людський підсумок для картки звіту («головне
відхилення — холодна піца і 25 хвилин запізнення») і відповідь у
підтримці за базою знань, коли не спрацював жоден сценарій.
Що не робить: не рахує бали, не приймає анкети, не вирішує про гроші.
"""
import json
import urllib.error
import urllib.request

import сховище

_КОНФ = None


def _конф():
    global _КОНФ
    if _КОНФ is None:
        к = сховище.конфіг()
        _КОНФ = {"ключ": к.get("OPENAI_API_KEY", ""), "модель": к.get("OPENAI_MODEL") or "gpt-5.6-luna"}
    return _КОНФ


def увімкнено():
    return bool(_конф()["ключ"])


def спитати(система, запит, макс=400):
    if not увімкнено():
        return None
    тіло = json.dumps({"model": _конф()["модель"], "max_completion_tokens": макс,
                       "messages": [{"role": "system", "content": система}, {"role": "user", "content": запит}]}).encode()
    req = urllib.request.Request("https://api.openai.com/v1/chat/completions", data=тіло,
                                 headers={"Content-Type": "application/json", "Authorization": f"Bearer {_конф()['ключ']}"})
    try:
        with urllib.request.urlopen(req, timeout=40) as r:
            в = json.loads(r.read())
        текст = в["choices"][0]["message"]["content"].strip()
        print(f"мозок: {в.get('usage', {}).get('total_tokens', '?')} токенів")
        return текст or None
    except (urllib.error.URLError, KeyError, ValueError, TimeoutError, OSError) as e:
        print(f"мозок не відповів: {str(e)[:100]}")
        return None


ПЕРСОНА_ЗВІТУ = ("Ти — агент програми тайного покупця мережі доставки Каппі (Одеса). Пишеш українською, "
                 "коротко і по суті, без емодзі, без оцінних слів про людей. Тільки факти з анкети. До 3 речень.")


def підсумок_звіту(п):
    """2–3 речення про головні відхилення — для картки в чат."""
    о = п.get("оцінка") or {}
    в = п["анкета"]["відповіді"]
    факти = {
        "загальна": о.get("загальна"), "зона": о.get("зона"),
        "групи": {г: гр.get("відсоток") for г, гр in (о.get("групи") or {}).items()},
        "критичні": [к["що"] for к in о.get("критичні", [])],
        "час_доставки_хв": о.get("час_доставки_хв"), "обіцяний": в.get("обіцяний_час"),
        "враження": в.get("заг_враження"), "виправити": в.get("заг_виправити"), "коментар_кухня": в.get("кух_коментар"),
    }
    return спитати(ПЕРСОНА_ЗВІТУ, "Склади підсумок для керівників за фактами:\n" + json.dumps(факти, ensure_ascii=False))


ПЕРСОНА_ПІДТРИМКИ = ("Ти — підтримка тайних покупців мережі Каппі в Telegram. Відповідаєш українською, тепло і коротко. "
                     "Правила: тайник не розкриває себе; позиції немає — пише в підтримку до оформлення; фото обов'язкові: "
                     "екран підтвердження, в упаковці, без упаковки, в розрізі, чек; анкету здати за 24 год після отримання; "
                     "гроші — після приймання анкети, переказує адміністратор, зазвичай до 3 робочих днів; кулдаун між "
                     "перевірками — два місяці. Якщо питання про гроші, конкретне замовлення або форс-мажор — скажи, що "
                     "передаєш координатору. Не вигадуй фактів.")


def відповідь_підтримки(питання):
    return спитати(ПЕРСОНА_ПІДТРИМКИ, питання, макс=250)


ПЕРСОНА_ПРИЙМАННЯ = ("Ти — агент програми тайного покупця Каппі. Маркетолог приймає анкету і читає твою пропозицію. "
                     "Пиши українською, 2–3 речення, без емодзі: що зробити з анкетою (прийняти / повернути на доробку / "
                     "розібрати), що з виплатою, чи заводити тікет і на кого. Спирайся лише на факти нижче, нічого не вигадуй.")


def пропозиція(п):
    """Розгорнута пропозиція для картки на ревю; без ключа — None (лишається правило)."""
    р = п.get("приймання") or {}
    о = п.get("оцінка") or {}
    факти = {"рекомендація_правила": р.get("рекомендація"), "чому": р.get("чому"),
             "автоперевірки": [{"що": x["що"], "ок": x["ок"], "деталь": x["деталь"]} for x in р.get("перевірки", [])],
             "оцінка": о.get("загальна"), "групи": {г: гр.get("відсоток") for г, гр in (о.get("групи") or {}).items()},
             "критичні": [к["що"] for к in о.get("критичні", [])],
             "syrve": (п.get("syrve") or {}).get("збіги"),
             "запізнення_хв": о.get("запізнення_хв"), "враження": п["анкета"]["відповіді"].get("заг_враження")}
    return спитати(ПЕРСОНА_ПРИЙМАННЯ, json.dumps(факти, ensure_ascii=False), макс=220)
