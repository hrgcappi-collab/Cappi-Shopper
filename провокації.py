#!/usr/bin/env python3
"""Провокації — ТЗ розділ 12. Каталог у провокації.json.

Правила, які виконує генератор:
- не частіше ніж в одному завданні з трьох (дивимось на два попередні
  видані завдання);
- не більше однієї на замовлення;
- лише рівень 1; рівень 2 — тільки руками маркетолога з дозволу COO;
- адресат має відповідати каналу: оператора провокуємо по телефону,
  точку — на самовивозі;
- провокація-скарга породжує тікет з ознакою «тестове звернення».

Захист співробітників (одного не частіше разу на квартал) перевіряється
після звірки з Syrve, коли відомо, хто саме працював: якщо той самий
оператор чи кур'єр уже потрапляв під провокацію у кварталі — результат
позначається «повтор, не для кадрових рішень».
"""
import json
import os

import перевірки

ТУТ = os.path.dirname(os.path.abspath(__file__))
_каталог = None


def каталог():
    """Каталог: правлений маркетологом (~/.shopper/провокації.json), інакше з коду."""
    global _каталог
    if _каталог is None:
        import сховище
        свій = сховище.json_читати("провокації.json", None)
        if свій and свій.get("провокації"):
            _каталог = свій
        else:
            with open(os.path.join(ТУТ, "провокації.json"), encoding="utf-8") as f:
                _каталог = json.load(f)
    return _каталог


def оновити(новий, хто):
    global _каталог
    import сховище, журнал
    if not isinstance(новий, dict) or not isinstance(новий.get("провокації"), list):
        return None, ["потрібен об'єкт зі списком «провокації»"]
    збережений = _каталог
    _каталог = {"версія": "?", "провокації": новий["провокації"]}
    помилки = перевірити()
    if помилки:
        _каталог = збережений
        return None, помилки
    from datetime import datetime
    _каталог = {"версія": datetime.now().strftime("%Y-%m-%d"), "провокації": новий["провокації"],
                "змінено": {"хто": хто, "коли": datetime.now().isoformat(timespec="seconds")}}
    сховище.json_писати("провокації.json", _каталог)
    журнал.запис(хто, "провокації:оновлено", _каталог["версія"], f"{len(новий['провокації'])} сценаріїв")
    return _каталог["версія"], []


def за_кодом(код):
    return next((п for п in каталог()["провокації"] if п["код"] == код), None)


def доступні(канал, рівень=1):
    return [п for п in каталог()["провокації"] if п["рівень"] <= рівень and канал in п.get("канали", [])]


def _останні_завдання(скільки=2):
    видані = sorted((п for п in перевірки.усі() if п.get("завдання")), key=lambda п: п["завдання"]["згенеровано"])
    return видані[-скільки:]


def можна_призначити():
    """Одна з трьох: якщо серед двох попередніх уже була — ні."""
    return not any((п["завдання"] or {}).get("провокація") for п in _останні_завдання(2))


def _скільки_разів(код, днів=90):
    from datetime import datetime, timedelta
    від = (datetime.now() - timedelta(days=днів)).isoformat()
    return sum(1 for п in перевірки.усі()
               if ((п.get("завдання") or {}).get("провокація") or {}).get("код") == код and п["завдання"]["згенеровано"] >= від)


def обрати(канал):
    """Найрідше вживана з доступних для каналу, або None."""
    if not можна_призначити():
        return None
    варіанти = доступні(канал)
    if not варіанти:
        return None
    п = min(варіанти, key=lambda x: (_скільки_разів(x["код"]), x["код"]))
    return {k: п[k] for k in ("код", "адресат", "дія", "що_перевіряємо", "еталон_реакції")} | {"тестове_звернення": п.get("тестове_звернення", False)}


def повтор_по_співробітнику(п):
    """Той самий оператор/кур'єр уже був під провокацією цього кварталу?"""
    from datetime import datetime, timedelta
    пров = (п.get("завдання") or {}).get("провокація")
    з = (п.get("syrve") or {}).get("замовлення") or {}
    if not пров or not з:
        return False
    хто = з.get("оператор") if пров["адресат"] == "оператор" else з.get("курєр") if пров["адресат"] == "курєр" else None
    if not хто:
        return False
    від = (datetime.now() - timedelta(days=90)).isoformat()
    for інша in перевірки.усі():
        if інша["id"] == п["id"] or not (інша.get("завдання") or {}).get("провокація"):
            continue
        зз = (інша.get("syrve") or {}).get("замовлення") or {}
        if інша["завдання"]["згенеровано"] >= від and хто in (зз.get("оператор"), зз.get("курєр")):
            return True
    return False


def перевірити():
    помилки, коди = [], set()
    for п in каталог()["провокації"]:
        for поле in ("код", "адресат", "рівень", "дія", "що_перевіряємо", "еталон_реакції"):
            if поле not in п:
                помилки.append(f"провокація {п.get('код')}: немає поля {поле}")
        if п.get("код") in коди:
            помилки.append(f"провокація: код повторюється {п['код']}")
        коди.add(п.get("код"))
        if п.get("рівень") == 1 and not п.get("канали"):
            помилки.append(f"провокація {п.get('код')}: рівень 1 без каналів")
    return помилки
