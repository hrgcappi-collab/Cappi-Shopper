#!/usr/bin/env python3
"""Перевірка — центральна сутність (ТЗ розділ 3). Один номер П-0416 на
все: завдання, анкету, оцінку і виплату; заявка на виплату — той самий
номер з префіксом В-. Інакше одна подія обговорюється під чотирма
номерами.

Статуси:
    запланована → завдання видано → акцептовано → в виконанні →
    анкета здана → на автоперевірці → на ревю → прийнята /
    на доробці / відхилена → закрита.  Глухий кут: зрив.
"""
from datetime import datetime

import журнал
import сховище

ФАЙЛ = "перевірки.json"
СТАТУСИ = ["запланована", "завдання видано", "акцептовано", "в виконанні", "анкета здана",
           "на автоперевірці", "на ревю", "прийнята", "на доробці", "відхилена", "закрита", "зрив"]
АКТИВНІ = {"завдання видано", "акцептовано", "в виконанні", "анкета здана", "на автоперевірці", "на ревю", "на доробці"}


def _всі():
    return сховище.json_читати(ФАЙЛ, {})


def _зберегти():
    сховище.json_писати(ФАЙЛ, _всі())


def _номер():
    л = сховище.json_читати("лічильники.json", {})
    л["перевірка"] = л.get("перевірка", 0) + 1
    сховище.json_писати("лічильники.json", л)
    return f"П-{л['перевірка']:04d}"


def дай(id_):
    return _всі().get(id_)


def усі(статус=None):
    return [п for п in _всі().values() if статус is None or п["статус"] == статус]


def зберегти(п):
    _всі()[п["id"]] = п
    _зберегти()


def створити(слот, хвиля_id):
    п = {"id": _номер(), "статус": "запланована", "тайник": None, "хвиля": хвиля_id,
         "слот": слот["id"], "філія": слот["філія"], "канал": слот["канал"],
         "вікно": {"дата": слот["дата"], "від": слот["від"], "до": слот["до"]},
         "завдання": None, "анкета": {"версія": None, "відповіді": {}, "здано": None, "етап_до": None},
         "оцінка": None, "приймання": None, "виплата": None,
         "історія": [], "створено": datetime.now().isoformat(timespec="seconds")}
    зберегти(п)
    return п


def статус(п, новий, хто="агент", чому=""):
    старий = п["статус"]
    п["статус"] = новий
    п["історія"].append({"коли": datetime.now().isoformat(timespec="seconds"), "з": старий, "у": новий, "хто": хто, "чому": чому})
    зберегти(п)
    журнал.запис(хто, f"перевірка:{новий}", п["id"], чому or f"був «{старий}»")
    return п


def тайника(uid, активна=True):
    """Поточна перевірка людини (одна активна за раз) або None."""
    for п in sorted(_всі().values(), key=lambda x: x["id"], reverse=True):
        if п.get("тайник") == uid and (not активна or п["статус"] in АКТИВНІ):
            return п
    return None


def історія_тайника(uid):
    return [п for п in _всі().values() if п.get("тайник") == uid]


def за_період(від, до=None, статуси=None):
    return [п for п in _всі().values()
            if п["вікно"]["дата"] >= від and (до is None or п["вікно"]["дата"] < до)
            and (статуси is None or п["статус"] in статуси)]


def відповідь(п, код):
    return п.get("анкета", {}).get("відповіді", {}).get(код)
