#!/usr/bin/env python3
"""Звернення тайників у підтримку — ТЗ розділ 17.

Кожне повідомлення в підтримку — запис; відповідь координатора закриває
всі відкриті звернення цієї людини. SLA: під час активного завдання —
30 хвилин у робочий час, інакше — доба. Прострочене — нагадування
координаторам, один раз на звернення.
"""
from datetime import datetime, timedelta

import налаштування
import перевірки
import сховище

ФАЙЛ = "звернення.json"


def _всі():
    return сховище.json_читати(ФАЙЛ, {})


def _зберегти():
    сховище.json_писати(ФАЙЛ, _всі())


def нове(uid, текст, бот_відповів):
    всі = _всі()
    з = {"id": f"З{len(всі) + 1:04d}", "uid": uid, "коли": datetime.now().isoformat(timespec="seconds"),
         "текст": текст, "бот_відповів": bool(бот_відповів), "відповіли": None, "нагадано": False,
         "активне_завдання": bool(перевірки.тайника(uid))}
    всі[з["id"]] = з
    _зберегти()
    return з


def відповіли(uid, хто):
    всі = _всі()
    for з in всі.values():
        if з["uid"] == uid and not з["відповіли"]:
            з["відповіли"] = {"коли": datetime.now().isoformat(timespec="seconds"), "хто": хто}
    _зберегти()


def _робочий_час(t):
    від, до = налаштування.дай("робочі_години")
    return від <= t.strftime("%H:%M") <= до


def прострочені(зараз=None):
    """Відкриті звернення понад SLA, про які ще не нагадували."""
    зараз = зараз or datetime.now()
    sla_хв = налаштування.дай("sla_підтримки_хв")
    res = []
    for з in _всі().values():
        if з["відповіли"] or з["нагадано"]:
            continue
        коли = datetime.fromisoformat(з["коли"])
        межа = timedelta(minutes=sla_хв) if з["активне_завдання"] and _робочий_час(зараз) else timedelta(hours=24)
        if зараз - коли > межа:
            res.append(з)
    return res


def нагадано(з):
    _всі()[з["id"]]["нагадано"] = True
    _зберегти()


def відкриті():
    return [з for з in _всі().values() if not з["відповіли"]]
